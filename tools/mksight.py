#!/usr/bin/env python3
"""The gunsight (the ST's D_0732A), as Baron source: its pixels as runs.

    mksight.py PRG OUT          write OUT (build/gen/sight.6502)

PRG is the ST's AUTO/STAR.PRG. The bitmap (docs/research/st-panel.md,
section 6) is a header (the words a row, the rows, the hotspot's x and y)
and then each row's words, a 16-pixel group's four planes at a time. The
blit (&09842) writes it unmasked onto the window just cleared, under the
dots and the objects, which OR over it, so its set pixels are what it
draws: the port draws them as horizontal runs, then what's left as
vertical ones, each a line for the line drawer (and its erase list), from
the sight's place.

Every set pixel must be colour 15 (all four planes), as the ST's is: the
port draws the sight in one colour, the ST's 15 (asserted here).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import st_prg  # noqa: E402

SIGHT = 0x0732A


def pixels(prg):
    words, rows, hx, hy = (prg.s16(SIGHT + 2 * i) for i in range(4))
    assert words % 4 == 0, words
    at = SIGHT + 8
    lit = set()
    for r in range(rows):
        for g in range(words // 4):
            planes = [prg.u16(at + 2 * (4 * g + k)) for k in range(4)]
            for b in range(16):
                c = sum(((planes[k] >> (15 - b)) & 1) << k for k in range(4))
                assert c in (0, 15), f"row {r}: colour {c}"
                if c:
                    lit.add((16 * g + b - hx, r - hy))
        at += 2 * words
    return lit


def runs(lit):
    """Horizontal runs of two or more, then the rest as vertical runs (a
    single pixel among them), each (x0, y0, x1, y1) from the hotspot."""
    out, left = [], set(lit)
    for y in sorted({y for _, y in lit}):
        xs = sorted(x for x, yy in lit if yy == y)
        i = 0
        while i < len(xs):
            j = i
            while j + 1 < len(xs) and xs[j + 1] == xs[j] + 1:
                j += 1
            if j > i:
                out.append((xs[i], y, xs[j], y))
                left -= {(x, y) for x in xs[i:j + 1]}
            i = j + 1
    for x in sorted({x for x, _ in left}):
        ys = sorted(y for xx, y in left if xx == x)
        i = 0
        while i < len(ys):
            j = i
            while j + 1 < len(ys) and ys[j + 1] == ys[j] + 1:
                j += 1
            out.append((x, ys[i], x, ys[j]))
            i = j + 1
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    prg = st_prg.load(sys.argv[1])
    r = runs(pixels(prg))
    lines = ["\\ Generated by tools/mksight.py from the ST's STAR.PRG: do not edit.",
             "",
             "\\ The gunsight (D_0732A) as runs of pixels from the sight's place, each",
             "\\ x0, y0, x1, y1 (signed bytes), for the line drawer.",
             f"SIGHT_RUNS = {len(r)}"]
    for k, name in enumerate(("sight_x0", "sight_y0", "sight_x1", "sight_y1")):
        lines.append(f".{name}")
        lines.append("    EQUB " + ", ".join(str(run[k] & 0xFF) for run in r))
    Path(sys.argv[2]).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()

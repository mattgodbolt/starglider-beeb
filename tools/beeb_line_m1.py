"""Generate a MODE 1 EOR line drawer (Baron source) for tools/beeb_linebench.mjs.

    python3 -I tools/beeb_line_m1.py > line_m1.6502 && baron line_m1.6502 -p OUTDIR

The screen is 256 x 160 in 4 colours (MODE 1 cut to 64 columns, R1 = 64), so a
character row is 512 bytes. The routine follows Nick Jameson's MODE 4 design as
kieranhj/line-test has it (nj-linedraw4.asm), moved to 2 bits a pixel:

- one unrolled block per pixel position (4 to a byte), with the slope's dx and
  dy self-modified into each block's SBC and ADC, and the colour into its masks;
- the Bresenham error in A, carry kept set across the loop (no SEC);
- shallow lines gather a byte's run of pixels in X and write the byte once
  (one EOR read-modify-write per byte-row run, not per pixel);
- the count is of minor-axis steps only, with NJ's trick for the last run:
  after the final step the error is lowered by its starting value, so the next
  step falls just past the end point and finishes the line.

Lines are always drawn upwards (y0 >= y1 after a swap), as NJ draws them, so a
row step is DEY with the carry untouched. Both end points are lit. It needs the
65C12 (JMP (abs,X), BRA).
"""

SCREEN = 0x3000

PIX = [0x88, 0x44, 0x22, 0x11]  # one pixel at position p (0 = leftmost)
RF = [0xFF, 0x77, 0x33, 0x11]  # pixels p..3
LT = [0x88, 0xCC, 0xEE, 0xFF]  # pixels 0..p

out = []


def emit(s=""):
    out.append(s)


emit(f"""; Generated by tools/beeb_line_m1.py: do not edit.
SCREEN = &{SCREEN:04X}
x0 = &70 : y0 = &71 : x1 = &72 : y1 = &73
scr = &74 : err = &76 : errs = &77 : cnt = &78 : ls = &79 : dx = &7A : dy = &7B

SECTION LineM1, org = &1000, filename = "LINEM1", cmos = TRUE
.start

; line: draw (x0, y0) to (x1, y1) in the colour set_colour last set.
.line
    LDA y0 : SEC : SBC y1 : BCS dyok
    LDX x0 : LDY x1 : STY x0 : STX x1      ; draw upwards: swap the ends
    LDX y0 : LDY y1 : STY y0 : STX y1
    EOR #&FF : ADC #1                      ; C = 0 from the borrow
.dyok
    STA dy
    LDA y0 : AND #&F8 : LSR A : LSR A      ; character row * 2, C = 0
    ADC #HI(SCREEN) : STA scr+1
    LDA x0 : AND #&FC : ASL A : STA scr    ; byte column * 8; C = x0 >= 128
    BCC addr_ok
    INC scr+1
.addr_ok
    LDA y0 : AND #7 : TAY
    LDA x0 : AND #3 : ASL A : TAX          ; entry block * 2
    LDA x1 : SEC : SBC x0 : BCS rightward
    EOR #&FF : ADC #1                      ; |dx|
    CMP dy : BCC steep_l : BEQ steep_l : JMP shallow_l
.rightward
    CMP dy : BCC steep_r : BEQ steep_r : JMP shallow_r
""")


# ---- set-up for each variant ------------------------------------------------
for v, kind in (("tr", "steep_r"), ("tl", "steep_l"), ("sr", "shallow_r"), ("sl", "shallow_l")):
    steep = v[0] == "t"
    emit(f".{kind}")
    emit("    STA dx")
    if steep:
        # SBC #dx in every block, ADC #dy; count x-steps
        emit("    CMP #0                          ; STA set no flags: Z is still CMP dy's")
        emit(f"    BEQ {v}_single")
        for p in range(4):
            emit(f"    STA {v}_sbc{p}+1")
        emit("    STA cnt")
        emit("    LDA #2 : STA ls")
        emit("    LDA dy")
        for p in range(4):
            emit(f"    STA {v}_adc{p}+1")
        emit("    LSR A : STA errs")
        emit(f"    SEC : JMP ({v}_entry,X)")
        emit(f".{v}_single                       ; vertical: one virtual step after dy rows")
        emit("    LDA #1")
        for p in range(4):
            emit(f"    STA {v}_sbc{p}+1")
        emit("    STA cnt : STA ls")
        emit(f"    LDA dy : SEC : JMP ({v}_entry,X)")
    else:
        for p in range(4):
            emit(f"    STA {v}_adc{p}+1")
        emit("    LDA dy")
        emit(f"    BEQ {v}_single")
        for p in range(4):
            emit(f"    STA {v}_sbc{p}+1")
        emit("    STA cnt")
        emit("    LDA #2 : STA ls")
        emit("    LDA dx : LSR A : STA errs")
        emit(f"    SEC : JMP ({v}_entry,X)")
        emit(f".{v}_single                       ; horizontal: one virtual step after dx pixels")
        emit("    LDA #1")
        for p in range(4):
            emit(f"    STA {v}_sbc{p}+1")
        emit("    STA cnt : STA ls")
        emit(f"    LDA dx : SEC : JMP ({v}_entry,X)")
    emit()


# ---- steep blocks ------------------------------------------------------------
# One pixel a row. Rightwards the blocks run 0,1,2,3 and an x-step falls into
# the next; leftwards they run 3,2,1,0.
for v, order, step in (("tr", [0, 1, 2, 3], +1), ("tl", [3, 2, 1, 0], -1)):
    emit(f"; ---- steep, {'right' if step > 0 else 'left'}wards ----")
    emit(f"ALIGN 256")
    for i, p in enumerate(order):
        last = i == 3
        emit(f".{v}_s{p}")
        emit("    TAX")
        emit(f".{v}_s{p}x")
        emit(f".{v}_m{p}")
        emit(f"    LDA #&{PIX[p]:02X}                    ; colour & pixel {p}, patched")
        emit("    EOR (scr),Y : STA (scr),Y")
        emit("    TXA")
        emit("    DEY")
        emit(f"    BMI {v}_row{p}")
        emit(f".{v}_t{p}")
        emit(f".{v}_sbc{p}")
        emit("    SBC #0                          ; dx, patched")
        emit(f"    BCS {v}_s{p}")
        emit(f".{v}_adc{p}")
        emit("    ADC #0                          ; dy, patched; C = 1 after")
        emit("    DEC cnt")
        emit(f"    BEQ {v}_e{p}")
        emit(f".{v}_x{p}")
        if not last:
            pass  # falls into the next position's block
        else:
            # next byte: column +8 (rightwards) or -8 (leftwards), C = 1 here
            emit("    TAX")
            emit("    LDA scr")
            if step > 0:
                emit("    ADC #7 : STA scr")
                emit(f"    BCC {v}_col_ok")
                emit("    INC scr+1")
            else:
                emit("    SBC #8 : STA scr")
                emit(f"    BCS {v}_col_ok")
                emit("    DEC scr+1")
            emit(f".{v}_col_ok")
            emit("    TXA : SEC")
            emit(f"    BRA {v}_s{order[0]}x")
    for p in order:
        emit(f".{v}_row{p}                           ; up a character row")
        emit("    DEC scr+1 : DEC scr+1 : LDY #7")
        emit(f"    BRA {v}_t{p}")
        emit(f".{v}_e{p}                             ; the last x-step, or the virtual one")
        emit("    DEC ls")
        emit(f"    BEQ {v}_done")
        emit("    SBC errs : INC cnt")
        emit(f"    BCS {v}_x{p}")
        emit(f"    BRA {v}_done                   ; the end-run trick failed: the check will see it")
    emit(f".{v}_done")
    emit("    RTS")
    emit(f".{v}_entry")
    emit("    EQUW " + ", ".join(f"{v}_s{p}" for p in range(4)))
    emit()

# ---- shallow blocks ----------------------------------------------------------
# A pixel with no y-step costs SBC + BCS. X holds the run mask from the pixel
# the run started at; a y-step trims it at this pixel and writes the byte.
for v, order, step in (("sr", [0, 1, 2, 3], +1), ("sl", [3, 2, 1, 0], -1)):
    emit(f"; ---- shallow, {'right' if step > 0 else 'left'}wards ----")
    emit("ALIGN 256")
    start_mask = RF if step > 0 else LT
    trim_mask = LT if step > 0 else RF
    for i, p in enumerate(order):
        last = i == 3
        nxt = order[i + 1] if not last else None
        emit(f".{v}_s{p}")
        emit(f".{v}_a{p}")
        emit(f"    LDX #&{start_mask[p]:02X}                    ; colour & run from pixel {p}, patched")
        emit(f".{v}_b{p}")
        emit(f".{v}_sbc{p}")
        emit("    SBC #0                          ; dy, patched")
        emit(f"    BCS {v}_b{nxt}" if not last else f"    BCS {v}_byte")
        emit(f".{v}_adc{p}")
        emit("    ADC #0                          ; dx, patched; C = 1 after")
        emit("    STA err")
        emit("    TXA")
        if trim_mask[p] != 0xFF:
            emit(f"    AND #&{trim_mask[p]:02X}")
        emit("    EOR (scr),Y : STA (scr),Y")
        emit("    DEC cnt")
        emit(f"    BEQ {v}_e{p}")
        emit(f".{v}_f{p}")
        emit("    DEY")
        emit(f"    BMI {v}_row{p}")
        emit(f".{v}_g{p}")
        if not last:
            emit("    LDA err")  # falls into the next block's run start
        else:
            emit(f"    BRA {v}_next")
    # the byte is done: next column, run starting at its first pixel
    emit(f".{v}_byte                             ; end of a byte with no y-step: C = 1")
    emit("    STA err")
    emit("    TXA")
    emit("    EOR (scr),Y : STA (scr),Y")
    emit(f".{v}_next")
    emit("    LDA scr")
    if step > 0:
        emit("    ADC #7 : STA scr                 ; C = 1 on every path here: +8")
        emit(f"    BCC {v}_col_ok")
        emit("    INC scr+1")
    else:
        emit("    SBC #8 : STA scr                 ; C = 1 on every path here")
        emit(f"    BCS {v}_col_ok")
        emit("    DEC scr+1")
    emit(f".{v}_col_ok")
    emit(f"    LDA err : SEC")
    emit(f"    JMP {v}_a{order[0]}")
    for p in order:
        emit(f".{v}_row{p}")
        emit("    DEC scr+1 : DEC scr+1 : LDY #7")
        emit(f"    BRA {v}_g{p}")
        emit(f".{v}_e{p}")
        emit("    DEC ls")
        emit(f"    BEQ {v}_done")
        emit("    LDA err : SBC errs : STA err : INC cnt")
        emit(f"    BCS {v}_f{p}")
        emit(f"    BRA {v}_done                   ; the end-run trick failed: the check will see it")
    emit(f".{v}_done")
    emit("    RTS")
    emit(f".{v}_entry")
    emit("    EQUW " + ", ".join(f"{v}_s{p}" for p in range(4)))
    emit()

# ---- colour ---------------------------------------------------------------------
emit("; set_colour: A = the colour's byte (&0F, &F0 or &FF for colours 1-3).")
emit(".set_colour")
emit("    TAX")
for p in range(4):
    emit(f"    TXA : AND #&{PIX[p]:02X} : STA tr_m{p}+1 : STA tl_m{p}+1")
    emit(f"    TXA : AND #&{RF[p]:02X} : STA sr_a{p}+1")
    emit(f"    TXA : AND #&{LT[p]:02X} : STA sl_a{p}+1")
emit("    RTS")
emit(".colour_init")
emit("    LDA #&FF : JMP set_colour")
emit(".end")
emit('PRINT "start ", ~start, " line ", ~line, " colour_init ", ~colour_init, " end ", ~end')
emit("ENDSECTION")

print("\n".join(out))

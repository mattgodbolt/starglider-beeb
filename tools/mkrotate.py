#!/usr/bin/env python3
"""Generate the camera rotation (Baron source): the ST's &04092, exactly,
and an approximation that decides which objects need it (decision 11).

    mkrotate.py > build/gen/rotate.6502

Every object near the player is rotated into camera space each step, and
the game's logic reads the result (docs/research/st.md), so each of the
nine terms must be the ST's floor(m d / 16384) to the bit. The matrix
changes only when the player turns, and rotate_setup specialises the code
to it then:

- each routine is a chain of jumps through the terms the matrix has,
  column by column (d's x, y, z): an entry of 0 has no link; one of
  +-16384 adds or subtracts d (the product is exact);
- any other entry m is a product by a 16-bit multiplier M, whose byte
  products are quarter-square table reads with the table offsets (M's
  bytes) patched into the code, so a product is only its reads;
- d is read as D = d + 32768, unsigned (its high byte's top bit flipped),
  which takes d's sign out of the products: m d = m D - 32768 m, so
  floor(m d / 16384) = floor(m D / 16384) - 2m, and each row's -2m goes
  into its constant, where its accumulator starts.

rotate_exact rotates rot_d (dx, dy, dz: signed words) into rot_acc (x', y',
z'). Its M is 4m as a word: for m >= 0 the term is the high word of the
32-bit product M D; for m < 0, M is 4m + 65536, which adds D to that high
word, so the term subtracts d too (and 32768, which the constant takes).

rotate_approx does the same from d's high bytes alone, each taken towards
0 as |d|'s is: each term M D_hi / 256 with M = 4|m|, added or subtracted
by m's sign (the constant is -2m again). That's within 444 units of the
exact result (each row of the matrix is a unit vector, so its terms'
errors, under 256 each, add to at most 256 times the square root of 3),
for under half the work. A matrix of only 0s and units has no products,
and then rotate_approx is exact: rot_exactly says so. The matrix is `cam`,
rows x', y', z' of words on x, y, z (render.6502).
"""

out = []


def emit(s=""):
    out.append(s)


# each product's patch sites, by what goes there: M's low byte, its
# complement, its high byte, its complement
KINDS = ["ml", "~ml", "mh", "~mh"]
EXACT_SITES = [("a", "ml"), ("b", "~ml"), ("c", "ml"), ("d", "~ml"),
               ("e", "mh"), ("f", "~mh"), ("g", "mh"), ("h", "~mh"),
               ("i", "ml"), ("j", "~ml"), ("k", "ml"), ("l", "~ml"),
               ("m", "mh"), ("n", "~mh"), ("o", "mh"), ("p", "~mh")]
# the approximation's, adding (M D_hi) and subtracting (the high byte's
# product read the other way round, f(Y - a) - f(Y + a), which is -a Y)
APPROX_SITES = [("a", "ml"), ("b", "~ml"), ("c", "mh"), ("d", "~mh"), ("e", "mh"), ("f", "~mh")]
APPROX_NEG_SITES = [("na", "ml"), ("nb", "~ml"), ("nc", "~mh"), ("nd", "mh"), ("ne", "~mh"), ("nf", "mh")]

# the terms in the chains' order: by column, then row
ORDER = [3 * i + j for j in range(3) for i in range(3)]


def term_name(e):
    i, j = divmod(e, 3)
    return f"{'xyz'[i]}' on {'xyz'[j]}"


emit("""\\ Generated by tools/mkrotate.py: do not edit.

\\ the rotations' operands and partial products
ZA_AUTO 6, rot_d            ; dx, dy, dz
ZA_AUTO 6, rot_acc          ; x', y', z'
ZA_AUTO1 rot_b3, rot_t1, rot_t2, rot_t3, rot_t4, rot_t5, rot_t6, rot_t7
""")

# Every term's code has the same shape, so each site is at the same offset
# from its term's start: rotate_setup patches and links any term through a
# pointer to it.
emit("\\ each kind of patch site's offsets from its term's start, and each")
emit("\\ variant's and its jump's (the exact terms' from rot0, the")
emit("\\ approximate terms' from rap0)")
for kind, name in zip(KINDS, ["ML", "NML", "MH", "NMH"]):
    sites = [k for k, v in EXACT_SITES if v == kind]
    emit(f"ROT_{name} = {{" + ", ".join(f"rot0_{k} + 1 - rot0" for k in sites) + "}")
    sites = [k for k, v in APPROX_SITES if v == kind]
    emit(f"RAP_{name} = {{" + ", ".join(f"rap0_{k} + 1 - rap0" for k in sites) + "}")
    sites = [k for k, v in APPROX_NEG_SITES if v == kind]
    emit(f"RAN_{name} = {{" + ", ".join(f"rap0_{k} + 1 - rap0" for k in sites) + "}")
for p in ["rot", "rap"]:
    P = p.upper()
    emit(f"{P}_GO = {p}0_go + 1 - {p}0")
    emit(f"{P}_ADD = {p}0_add - {p}0")
    emit(f"{P}_ADD_GO = {p}0_add_go + 1 - {p}0")
    emit(f"{P}_SUB = {p}0_sub - {p}0")
    emit(f"{P}_SUB_GO = {p}0_sub_go + 1 - {p}0")
    emit(f"{P}C_GO = {p}c0_go + 1 - {p}c0")
emit("RAP_NEG = rap0_n - rap0")
emit("RAP_NEG_GO = rap0_n_go + 1 - rap0")
for e in range(1, 9):
    for k in [k for k, _ in EXACT_SITES] + ["go", "add", "add_go", "sub", "sub_go"]:
        emit(f"ASSERT rot{e}_{k} - rot{e} = rot0_{k} - rot0")
    for k in [k for k, _ in APPROX_SITES + APPROX_NEG_SITES] + ["n", "n_go", "go", "add", "add_go", "sub", "sub_go"]:
        emit(f"ASSERT rap{e}_{k} - rap{e} = rap0_{k} - rap0")
for j in range(1, 3):
    emit(f"ASSERT rotc{j}_go - rotc{j} = rotc0_go - rotc0")
    emit(f"ASSERT rapc{j}_go - rapc{j} = rapc0_go - rapc0")
emit()


def patch(var, prefix, name, complement):
    emit(f"    LDA {var}" + (" : EOR #&FF" if complement else ""))
    emit(f"    FOR o = {prefix}_{name}")
    emit("        LDY #o : STA (t),Y")
    emit("    NEXT")


emit("""\\ rotate_setup: specialise rotate_exact and rotate_approx to cam, once a
\\ camera: each term's sites patched, and its links made, in the chains'
\\ order (term), then each row's constant and rot_exactly.
.rotate_setup
{
    ZA_AUTO2 m, mag, t, asite, esite, astub, estub
    ZA_AUTO 6, ka, ke           ; the rows' constants
    ZA_AUTO1 row, seen, prods, msign
    LDX #5
    ZA_DISCARD ka, ke
.clear
    STZ ka,X : ZA_INDEXEDBY 0..5
    STZ ke,X : ZA_INDEXEDBY 0..5
    DEX : BPL clear
    STZ prods
    LDA #LO(rap_go + 1) : STA asite : LDA #HI(rap_go + 1) : STA asite+1
    LDA #LO(rot_go + 1) : STA esite : LDA #HI(rot_go + 1) : STA esite+1""")
for j in range(3):
    emit(f"    \\ column {'xyz'[j]}")
    emit("    STZ seen")
    emit(f"    LDA #LO(rapc{j}) : STA astub : LDA #HI(rapc{j}) : STA astub+1")
    emit(f"    LDA #LO(rotc{j}) : STA estub : LDA #HI(rotc{j}) : STA estub+1")
    for i in range(3):
        emit(f"    LDA #{2 * i} : STA row : LDX #{3 * i + j} : JSR term")
emit("""    \\ the chains' ends
    LDA #LO(rap_done) : STA (asite) : LDY #1 : LDA #HI(rap_done) : STA (asite),Y
    LDA #LO(rot_done) : STA (esite) : LDA #HI(rot_done) : STA (esite),Y
    \\ the constants, into the accumulators' first values""")
for r in range(6):
    emit(f"    LDA ka+{r} : STA rap_k{r}+1 : LDA ke+{r} : STA rot_k{r}+1")
emit("""    \\ no products: the approximation is exact
    LDA prods : EOR #&80 : STA rot_exactly
    \\ the identity: d needs no rotating at all
    STZ rot_identity
    LDX #17
.identity
    LDA cam,X : ZA_INDEXEDBY 0..17
    CMP rot_unit,X : BNE rotated
    DEX : BPL identity
    LDA #&80 : STA rot_identity
.rotated
    RTS

\\ term: cam's entry X (row row / 2) patched into both routines, and linked.
.term
    TXA : ASL A : TAY
    LDA cam,Y : ZA_INDEXEDBY {0, 2, 4, 6, 8, 10, 12, 14, 16}
    STA m : LDA cam+1,Y : ZA_INDEXEDBY {0, 2, 4, 6, 8, 10, 12, 14, 16}
    STA m+1 : STA msign
    ORA m : BNE live
    RTS                                 ; 0: no link
.live
    LDA m+1 : BPL positive
    LDA #0 : SEC : SBC m : STA mag : LDA #0 : SBC m+1 : STA mag+1
    BRA got
.positive
    STA mag+1 : LDA m : STA mag
.got
    LDA mag : BNE product
    LDA mag+1 : CMP #&40 : BNE product
    \\\\ +-16384: d added or subtracted, in both
    LDA rap_base_lo,X : STA t : LDA rap_base_hi,X : STA t+1
    BIT msign : BMI unit_sub
    LDA #RAP_ADD : LDY #RAP_ADD_GO : JSR alink
    LDA rot_base_lo,X : STA t : LDA rot_base_hi,X : STA t+1
    LDA #ROT_ADD : LDY #ROT_ADD_GO : JMP elink
.unit_sub
    LDA #RAP_SUB : LDY #RAP_SUB_GO : JSR alink
    LDA rot_base_lo,X : STA t : LDA rot_base_hi,X : STA t+1
    LDA #ROT_SUB : LDY #ROT_SUB_GO : JMP elink
.product
    LDA #&80 : STA prods
    \\\\ the constants: -2m in both, and the exact's 32768 for m < 0
    LDY row
    LDA m : ASL A : STA t : LDA m+1 : ROL A : STA t+1
    LDA ka,Y : ZA_INDEXEDBY {0, 2, 4}
    SEC : SBC t : STA ka,Y : ZA_INDEXEDBY {0, 2, 4}
    LDA ka+1,Y : ZA_INDEXEDBY {0, 2, 4}
    SBC t+1 : STA ka+1,Y : ZA_INDEXEDBY {0, 2, 4}
    LDA ke,Y : ZA_INDEXEDBY {0, 2, 4}
    SEC : SBC t : STA ke,Y : ZA_INDEXEDBY {0, 2, 4}
    LDA ke+1,Y : ZA_INDEXEDBY {0, 2, 4}
    SBC t+1
    BIT msign : BPL no_half
    EOR #&80
.no_half
    STA ke+1,Y : ZA_INDEXEDBY {0, 2, 4}
    \\\\ a column's first product loads its D first
    LDA seen : BNE stubbed
    INC seen
    LDA astub : STA t : LDA astub+1 : STA t+1
    LDA #0 : LDY #RAPC_GO : JSR alink
    LDA estub : STA t : LDA estub+1 : STA t+1
    LDA #0 : LDY #ROTC_GO : JSR elink
.stubbed
    \\\\ the exact term: M = 4m, a word
    ASL m : ROL m+1 : ASL m : ROL m+1
    LDA rot_base_lo,X : STA t : LDA rot_base_hi,X : STA t+1
""")
patch("m", "ROT", "ML", False)
patch("m", "ROT", "NML", True)
patch("m+1", "ROT", "MH", False)
patch("m+1", "ROT", "NMH", True)
emit("""    LDA #0 : LDY #ROT_GO : JSR elink
    BIT msign : BPL exact_done
    LDA #ROT_SUB : LDY #ROT_SUB_GO : JSR elink
.exact_done
    \\\\ the approximate term: M = 4|m|, added or subtracted
    ASL mag : ROL mag+1 : ASL mag : ROL mag+1
    LDA rap_base_lo,X : STA t : LDA rap_base_hi,X : STA t+1
    BIT msign : BMI approx_neg
""")
patch("mag", "RAP", "ML", False)
patch("mag", "RAP", "NML", True)
patch("mag+1", "RAP", "MH", False)
patch("mag+1", "RAP", "NMH", True)
emit("    LDA #0 : LDY #RAP_GO : JMP alink")
emit(".approx_neg")
patch("mag", "RAN", "ML", False)
patch("mag", "RAN", "NML", True)
patch("mag+1", "RAN", "MH", False)
patch("mag+1", "RAN", "NMH", True)
emit("""    LDA #RAP_NEG : LDY #RAP_NEG_GO
    \\\\ (on into alink)

\\\\ alink, elink: the approximate or the exact chain on to the code at t + A,
\\\\ whose own jump is at t + Y.
.alink
    CLC : ADC t : STA (asite)
    LDA t+1 : ADC #0 : PHY : LDY #1 : STA (asite),Y : PLY
    TYA : CLC : ADC t : STA asite
    LDA t+1 : ADC #0 : STA asite+1
    RTS
.elink
    CLC : ADC t : STA (esite)
    LDA t+1 : ADC #0 : PHY : LDY #1 : STA (esite),Y : PLY
    TYA : CLC : ADC t : STA esite
    LDA t+1 : ADC #0 : STA esite+1
    RTS
}

\\ &80 while cam has no products, when rotate_approx is exact, and while it's
\\ the identity
.rot_exactly
    EQUB 0
.rot_identity
    EQUB 0
.rot_unit
    EQUW 16384, 0, 0, 0, 16384, 0, 0, 0, 16384
""")


def table(name, labels):
    emit(f".{name}_lo")
    emit("    EQUB " + ", ".join(f"LO({x})" for x in labels))
    emit(f".{name}_hi")
    emit("    EQUB " + ", ".join(f"HI({x})" for x in labels))


emit("\\ each term's code, by term")
table("rot_base", [f"rot{e}" for e in range(9)])
table("rap_base", [f"rap{e}" for e in range(9)])
emit()


def chain_after(prefix, e, variants, final):
    """Every link the chain can reach after term e's: the later terms'
    variants, the stubs of its column and the later ones (a column's stub
    comes before its first product), and the end."""
    later = ORDER[ORDER.index(e) + 1:]
    return ([f"{prefix}c{j}" for j in range(e % 3, 3)] +
            [v.format(f) for f in later for v in variants] + [final])


def units(prefix, e, j, acc, chain):
    emit(f".{prefix}{e}_add                      ; +16384: + d")
    emit(f"    CLC : LDA {acc} : ADC rot_d+{2 * j} : STA {acc}")
    emit(f"    LDA {acc}+1 : ADC rot_d+{2 * j + 1} : STA {acc}+1")
    emit(f".{prefix}{e}_add_go")
    emit(f"    JMP {prefix}_done                   ; patched: the next link")
    emit(f"    ZA_CANJUMP {', '.join(chain)}")
    emit(f".{prefix}{e}_sub                      ; -16384: - d")
    emit(f"    SEC : LDA {acc} : SBC rot_d+{2 * j} : STA {acc}")
    emit(f"    LDA {acc}+1 : SBC rot_d+{2 * j + 1} : STA {acc}+1")
    emit(f".{prefix}{e}_sub_go")
    emit(f"    JMP {prefix}_done                   ; patched: the next link")
    emit(f"    ZA_CANJUMP {', '.join(chain)}")


def start(prefix, name, what):
    first = ([f"{prefix}c{j}" for j in range(3)] +
             [f"{prefix}{e}_{u}" for e in ORDER for u in ("add", "sub")] + [f"{prefix}_done"])
    emit(f"\\ {name}: {what}")
    emit(f".{name}")
    for r in range(6):
        emit(f".{prefix}_k{r}")
        emit(f"    LDA #0 : STA rot_acc+{r}               ; patched: the rows' constants")
    emit(f".{prefix}_go")
    emit(f"    JMP {prefix}_done                   ; patched: the first link")
    emit(f"    ZA_CANJUMP {', '.join(first)}")


EXACT_VARIANTS = ["rot{}", "rot{}_add", "rot{}_sub"]
APPROX_VARIANTS = ["rap{}", "rap{}_n", "rap{}_add", "rap{}_sub"]


def stub(prefix, j, loads, variants):
    terms = [3 * i + j for i in range(3)]
    emit(f".{prefix}c{j}                          ; column {'xyz'[j]}'s D")
    for s in loads:
        emit(s if s.startswith(".") else f"    {s}")
    emit(f".{prefix}c{j}_go")
    emit(f"    JMP {prefix}_done                   ; patched: the column's first product")
    emit(f"    ZA_CANJUMP {', '.join(v.format(e) for e in terms for v in variants)}")


start("rot", "rotate_exact", "rot_acc = cam rot_d, as the ST's: X and Y are\n\\ each column's D, low and high byte.")
for j in range(3):
    stub("rot", j, [f"LDX rot_d+{2 * j}", f"LDA rot_d+{2 * j + 1} : EOR #&80 : TAY"], ["rot{}"])
    for i in range(3):
        e = 3 * i + j
        acc = f"rot_acc+{2 * i}"
        chain = chain_after("rot", e, EXACT_VARIANTS, "rot_done")
        emit(f"\\ term {e}: {term_name(e)}")
        emit(f".rot{e}                           ; M D's high word")
        emit("    SEC")
        emit(f".rot{e}_a")
        emit("    LDA sqr_lo,X")
        emit(f".rot{e}_b")
        emit("    SBC neg_lo,X                    ; M's low byte by D's: only its borrow")
        emit(f".rot{e}_c")
        emit("    LDA sqr_hi,X")
        emit(f".rot{e}_d")
        emit("    SBC neg_hi,X : STA rot_t1")
        emit("    SEC")
        emit(f".rot{e}_e")
        emit("    LDA sqr_lo,X")
        emit(f".rot{e}_f")
        emit("    SBC neg_lo,X : STA rot_t2       ; M's high byte by D's low")
        emit(f".rot{e}_g")
        emit("    LDA sqr_hi,X")
        emit(f".rot{e}_h")
        emit("    SBC neg_hi,X : STA rot_t3")
        emit("    SEC")
        emit(f".rot{e}_i")
        emit("    LDA sqr_lo,Y")
        emit(f".rot{e}_j")
        emit("    SBC neg_lo,Y : STA rot_t4       ; M's low byte by D's high")
        emit(f".rot{e}_k")
        emit("    LDA sqr_hi,Y")
        emit(f".rot{e}_l")
        emit("    SBC neg_hi,Y : STA rot_t5")
        emit("    SEC")
        emit(f".rot{e}_m")
        emit("    LDA sqr_lo,Y")
        emit(f".rot{e}_n")
        emit("    SBC neg_lo,Y : STA rot_t6       ; M's high byte by D's high")
        emit(f".rot{e}_o")
        emit("    LDA sqr_hi,Y")
        emit(f".rot{e}_p")
        emit("    SBC neg_hi,Y : STA rot_t7")
        emit("    \\ the second byte's carries into the third's (rot_t3 and rot_t5")
        emit("    \\ are at most &FE, the high bytes of byte products)")
        emit("    LDA rot_t1 : CLC : ADC rot_t2")
        emit(f"    BCC rot_c{e}")
        emit("    INC rot_t3")
        emit(f".rot_c{e}")
        emit("    CLC : ADC rot_t4")
        emit(f"    BCC rot_d{e}")
        emit("    INC rot_t5")
        emit(f".rot_d{e}")
        emit("    LDA rot_t3 : CLC : ADC rot_t5")
        emit(f"    BCC rot_e{e}")
        emit("    INC rot_t7")
        emit(f".rot_e{e}")
        emit("    CLC : ADC rot_t6")
        emit(f"    BCC rot_f{e}")
        emit("    INC rot_t7")
        emit(f".rot_f{e}")
        emit(f"    CLC : ADC {acc} : STA {acc}")
        emit(f"    LDA rot_t7 : ADC {acc}+1 : STA {acc}+1")
        emit(f".rot{e}_go")
        emit("    JMP rot_done                    ; patched: the next link")
        emit(f"    ZA_CANJUMP rot{e}_sub, {', '.join(chain)}")
        units("rot", e, j, acc, chain)
emit(".rot_done")
emit("    RTS")
emit()

start("rap", "rotate_approx", "rot_acc = cam rot_d from D's high bytes alone,\n\\ each column's in Y: each term M D_hi / 256.")
for j in range(3):
    stub("rap", j, [f"LDA rot_d+{2 * j + 1} : BPL rap_t{j}",
                    f"LDY rot_d+{2 * j} : BEQ rap_t{j}",
                    "INC A                           ; d_hi towards 0, as |d|'s is",
                    f".rap_t{j}",
                    "EOR #&80 : TAY"], ["rap{}", "rap{}_n"])
    for i in range(3):
        e = 3 * i + j
        acc = f"rot_acc+{2 * i}"
        chain = chain_after("rap", e, APPROX_VARIANTS, "rap_done")
        emit(f"\\ term {e}: {term_name(e)}")
        emit(f".rap{e}                           ; + M D_hi / 256")
        emit("    SEC")
        emit(f".rap{e}_a")
        emit("    LDA sqr_hi,Y")
        emit(f".rap{e}_b")
        emit("    SBC neg_hi,Y                    ; M's low byte by D_hi, its high byte")
        emit(f"    CLC : ADC {acc} : STA {acc}")
        emit(f"    BCC rap_c{e}")
        emit(f"    INC {acc}+1")
        emit(f".rap_c{e}")
        emit("    SEC")
        emit(f".rap{e}_c")
        emit("    LDA sqr_lo,Y")
        emit(f".rap{e}_d")
        emit("    SBC neg_lo,Y : TAX")
        emit(f".rap{e}_e")
        emit("    LDA sqr_hi,Y")
        emit(f".rap{e}_f")
        emit("    SBC neg_hi,Y : STA rot_b3       ; M's high byte by D_hi")
        emit(f"    TXA : CLC : ADC {acc} : STA {acc}")
        emit(f"    LDA rot_b3 : ADC {acc}+1 : STA {acc}+1")
        emit(f".rap{e}_go")
        emit("    JMP rap_done                    ; patched: the next link")
        emit(f"    ZA_CANJUMP {', '.join(chain)}")
        emit(f".rap{e}_n                         ; - M D_hi / 256")
        emit("    SEC")
        emit(f".rap{e}_na")
        emit("    LDA sqr_hi,Y")
        emit(f".rap{e}_nb")
        emit("    SBC neg_hi,Y : STA rot_t1       ; M's low byte by D_hi, its high byte")
        emit("    SEC")
        emit(f".rap{e}_nc")
        emit("    LDA neg_lo,Y")
        emit(f".rap{e}_nd")
        emit("    SBC sqr_lo,Y : TAX")
        emit(f".rap{e}_ne")
        emit("    LDA neg_hi,Y")
        emit(f".rap{e}_nf")
        emit("    SBC sqr_hi,Y : STA rot_b3       ; minus M's high byte by D_hi")
        emit(f"    TXA : CLC : ADC {acc} : STA {acc}")
        emit(f"    LDA rot_b3 : ADC {acc}+1 : STA {acc}+1")
        emit(f"    SEC : LDA {acc} : SBC rot_t1 : STA {acc}")
        emit(f"    BCS rap_n{e}")
        emit(f"    DEC {acc}+1")
        emit(f".rap_n{e}")
        emit(f".rap{e}_n_go")
        emit("    JMP rap_done                    ; patched: the next link")
        emit(f"    ZA_CANJUMP {', '.join(chain)}")
        units("rap", e, j, acc, chain)
emit(".rap_done")
emit("    RTS")
print("\n".join(out))

#!/usr/bin/env python3
"""Generate the camera rotation (Baron source): the ST's &04092, exactly,
and an approximation that decides which objects need it (decision 11).

    mkrotate.py > build/gen/rotate.6502

Every object near the player is rotated into camera space each frame, and
the game's logic reads the result (docs/research/st.md), so each of the
nine terms must be the ST's floor(m d / 16384) to the bit. The matrix is
the same for the whole frame, so rotate_setup specialises the code to it
once a frame:

- an entry of 0 skips its term; one of +-16384 adds or subtracts d (the
  product is exact);
- any other entry m is multiplied as M = 4|m|, which fits 16 bits, so the
  result is the 32-bit product's high word: its four byte products are
  quarter-square table reads whose table offsets (the multiplicand's
  bytes) are patched into the code, so a product is only its reads;
- a negative product's floor is the high word's complement when the low
  word isn't zero, and its negation when it is.

rotate_exact rotates rot_d (dx, dy, dz: signed words) into rot_acc (x', y',
z'). rotate_approx does the same from d's high bytes alone, each term
M |d_hi| / 256: within 444 units of the exact result (each row of the
matrix is a unit vector, so its terms' errors, under 256 each, add to at
most 256 times the square root of 3), for a quarter of the work. The
matrix is `cam`, rows x', y', z' of words on x, y, z (render.6502).
"""

out = []


def emit(s=""):
    out.append(s)


# each term's patch sites: (label suffix, what goes there)
EXACT_SITES = [("a", "ml"), ("b", "~ml"), ("c", "ml"), ("d", "~ml"),
               ("e", "mh"), ("f", "~mh"), ("g", "mh"), ("h", "~mh"),
               ("i", "ml"), ("j", "~ml"), ("k", "ml"), ("l", "~ml"),
               ("m", "mh"), ("n", "~mh"), ("o", "mh"), ("p", "~mh")]
APPROX_SITES = [("a", "ml"), ("b", "~ml"), ("c", "mh"), ("d", "~mh"), ("e", "mh"), ("f", "~mh")]
KINDS = ["ml", "~ml", "mh", "~mh"]

emit("""\\ Generated by tools/mkrotate.py: do not edit.

\\ the rotations' operands and partial products
ZA_AUTO 6, rot_d            ; dx, dy, dz
ZA_AUTO 6, rot_acc          ; x', y', z'
ZA_AUTO 3, rot_dl           ; |d|'s bytes, and d's signs
ZA_AUTO 3, rot_dh
ZA_AUTO 3, rot_s
ZA_AUTO1 rot_b0, rot_b1, rot_b2, rot_b3, rot_t1, rot_t2, rot_t3, rot_t4, rot_t5, rot_t6, rot_t7
""")

# Every term's code has the same shape, so each patch site is at the same
# offset from its term's start: rotate_setup patches any term through a
# pointer to it.
emit("\\ each kind of patch site's offsets from its term's start: M's low")
emit("\\ byte, its complement, its high byte, its complement; the exact")
emit("\\ terms' (rot0's) then the approximate terms' (rap0's)")
for kind, name in zip(KINDS, ["ML", "NML", "MH", "NMH"]):
    sites = [k for k, v in EXACT_SITES if v == kind]
    emit(f"ROT_{name} = {{" + ", ".join(f"rot0_{k} + 1 - rot0" for k in sites) + "}")
    sites = [k for k, v in APPROX_SITES if v == kind]
    emit(f"RAP_{name} = {{" + ", ".join(f"rap0_{k} + 1 - rap0" for k in sites) + "}")
for e in range(1, 9):
    for k, _ in EXACT_SITES:
        emit(f"ASSERT rot{e}_{k} - rot{e} = rot0_{k} - rot0")
    for k, _ in APPROX_SITES:
        emit(f"ASSERT rap{e}_{k} - rap{e} = rap0_{k} - rap0")
emit()
emit("""\\ rotate_setup: specialise rotate_exact and rotate_approx to cam, once a
\\ frame.
.rotate_setup
{
    ZA_AUTO2 m, site
    ZA_AUTO1 e, how
    STZ e
.term
    LDA e : ASL A : TAX
    LDA cam,X : ZA_INDEXEDBY {0, 2, 4, 6, 8, 10, 12, 14, 16}
    STA m : LDA cam+1,X : ZA_INDEXEDBY {0, 2, 4, 6, 8, 10, 12, 14, 16}
    STA m+1
    \\\\ the sign, into the exact term's two sign sites (the approximate
    \\\\ term reads them)
    AND #&80 : TAY
    LDA rot_sign_lo,X : STA site : LDA rot_sign_hi,X : STA site+1
    TYA : STA (site)
    LDA rot_sign_lo+1,X : STA site : LDA rot_sign_hi+1,X : STA site+1
    TYA : STA (site)
    LDA m+1 : BPL positive
    LDA #0 : SEC : SBC m : STA m : LDA #0 : SBC m+1 : STA m+1
.positive
    \\\\ how: 0 for the next term (an entry of 0), 1 a unit (+-16384), 2 a
    \\\\ product; into both terms' jumps
    LDA #0 : STA how
    LDA m : ORA m+1 : BEQ jumps
    INC how
    LDA m : BNE general : LDA m+1 : CMP #&40 : BEQ jumps
.general
    INC how
.jumps
    JSR jump
    INX
    JSR jump
    DEX
    LDA how : CMP #2 : BEQ product
    JMP done
.product
    ASL m : ROL m+1 : ASL m : ROL m+1        ; M = 4|m|
    \\\\ the exact term's sites, through a pointer to it
    LDA rot_jump_lo,X : STA site : LDA rot_jump_hi,X : STA site+1
""")
def patch(var, prefix, name, complement):
    emit(f"    LDA {var}" + (" : EOR #&FF" if complement else ""))
    emit(f"    FOR o = {prefix}_{name}")
    emit("        LDY #o : STA (site),Y")
    emit("    NEXT")
patch("m", "ROT", "ML", False)
patch("m", "ROT", "NML", True)
patch("m+1", "ROT", "MH", False)
patch("m+1", "ROT", "NMH", True)
emit("    \\ and the approximate term's")
emit("    LDA rot_jump_lo+1,X : STA site : LDA rot_jump_hi+1,X : STA site+1")
patch("m", "RAP", "ML", False)
patch("m", "RAP", "NML", True)
patch("m+1", "RAP", "MH", False)
patch("m+1", "RAP", "NMH", True)
emit(""".done
    INC e : LDA e : CMP #9 : BEQ finished
    JMP term
.finished
    RTS
\\\\ jump: the jump X names (rot_jump), to the term how says
.jump
    LDA rot_jump_lo,X : STA site : LDA rot_jump_hi,X : STA site+1
    LDY how : BEQ to_next
    DEY : BEQ to_unit
    LDA rot_mul_lo,X : LDY #1 : STA (site),Y
    LDA rot_mul_hi,X : INY : STA (site),Y
    RTS
.to_unit
    LDA rot_unit_lo,X : LDY #1 : STA (site),Y
    LDA rot_unit_hi,X : INY : STA (site),Y
    RTS
.to_next
    LDA rot_next_lo,X : LDY #1 : STA (site),Y
    LDA rot_next_hi,X : INY : STA (site),Y
    RTS
}
""")


def table(name, labels):
    emit(f".{name}_lo")
    emit("    EQUB " + ", ".join(f"LO({x})" for x in labels))
    emit(f".{name}_hi")
    emit("    EQUB " + ", ".join(f"HI({x})" for x in labels))


def pairs(f):
    """By term, two entries each: X = 2e for the first, 2e + 1 the second."""
    return [x for e in range(9) for x in f(e)]


def nxt(e):
    return f"rot{e + 1}" if e < 8 else "rot_done"


def anxt(e):
    return f"rap{e + 1}" if e < 8 else "rap_done"


table("rot_sign", pairs(lambda e: [f"rot{e}_sign+1", f"rot{e}_usign+1"]))
emit("\\ the exact and the approximate term's jumps, and their targets")
table("rot_jump", pairs(lambda e: [f"rot{e}", f"rap{e}"]))
table("rot_next", pairs(lambda e: [nxt(e), anxt(e)]))
table("rot_unit", pairs(lambda e: [f"rot{e}_unit", f"rap{e}_unit"]))
table("rot_mul", pairs(lambda e: [f"rot{e}_mul", f"rap{e}_mul"]))
emit()

emit("""\\ rotate_abs: rot_dl, rot_dh and rot_s from rot_d.
.rotate_abs
""")
for j in range(3):
    emit(f"    LDA rot_d+{2 * j + 1} : STA rot_s+{j} : BPL rot_dpos{j}")
    emit(f"    LDA #0 : SEC : SBC rot_d+{2 * j} : STA rot_dl+{j}")
    emit(f"    LDA #0 : SBC rot_d+{2 * j + 1} : STA rot_dh+{j}")
    emit(f"    JMP rot_dsigned{j}")
    emit(f".rot_dpos{j}")
    emit(f"    LDA rot_d+{2 * j} : STA rot_dl+{j} : LDA rot_d+{2 * j + 1} : STA rot_dh+{j}")
    emit(f".rot_dsigned{j}")
emit("    RTS")
emit()


def product(e, k0, lo, hi):
    """A byte product: the patched reads rot{e}_{k0}.. (sqr_lo, neg_lo,
    sqr_hi, neg_hi), Y the other byte."""
    k = [chr(ord(k0) + n) for n in range(4)]
    emit("    SEC")
    emit(f".rot{e}_{k[0]}")
    emit("    LDA sqr_lo,Y")
    emit(f".rot{e}_{k[1]}")
    emit(f"    SBC neg_lo,Y : STA {lo}")
    emit(f".rot{e}_{k[2]}")
    emit("    LDA sqr_hi,Y")
    emit(f".rot{e}_{k[3]}")
    emit(f"    SBC neg_hi,Y : STA {hi}")


def unit(prefix, e, j, acc, to):
    emit(f".{prefix}{e}_unit                        ; +-16384: +-d exactly")
    if prefix == "rot":
        emit(f".rot{e}_usign")
        emit("    LDA #0                          ; patched: the entry's sign")
    else:
        emit(f"    LDA rot{e}_usign+1               ; the entry's sign, as the exact term's")
    emit(f"    BMI {prefix}_usub{e}")
    emit(f"    CLC : LDA {acc} : ADC rot_d+{2 * j} : STA {acc}")
    emit(f"    LDA {acc}+1 : ADC rot_d+{2 * j + 1} : STA {acc}+1")
    emit(f"    JMP {to}")
    emit(f".{prefix}_usub{e}")
    emit(f"    SEC : LDA {acc} : SBC rot_d+{2 * j} : STA {acc}")
    emit(f"    LDA {acc}+1 : SBC rot_d+{2 * j + 1} : STA {acc}+1")
    emit(f"    JMP {to}")


emit("""\\ rotate_exact: rot_acc = cam rot_d, term by term as the ST's (rot_dl,
\\ rot_dh and rot_s from rotate_abs).
.rotate_exact
    STZ rot_acc : STZ rot_acc+1 : STZ rot_acc+2 : STZ rot_acc+3 : STZ rot_acc+4 : STZ rot_acc+5
""")
for e in range(9):
    i, j = divmod(e, 3)
    acc = f"rot_acc+{2 * i}"
    emit(f"\\ term {e}: {'xyz'[i]}' on {'xyz'[j]}")
    emit(f".rot{e}")
    emit(f"    JMP rot{e}_mul                   ; patched: the next term, rot{e}_unit or rot{e}_mul")
    emit(f"    ZA_CANJUMP rot{e}_mul, rot{e}_unit, {nxt(e)}")
    emit(f".rot{e}_mul")
    emit(f"    LDY rot_dl+{j}")
    product(e, "a", "rot_b0", "rot_t1")      # ML dl
    product(e, "e", "rot_t2", "rot_t3")      # MH dl
    emit(f"    LDY rot_dh+{j}")
    product(e, "i", "rot_t4", "rot_t5")      # ML dh
    product(e, "m", "rot_t6", "rot_t7")      # MH dh
    emit("    CLC : LDA rot_t1 : ADC rot_t2 : STA rot_b1")
    emit("    LDA rot_t3 : ADC rot_t5 : STA rot_b2")
    emit("    LDA rot_t7 : ADC #0 : STA rot_b3")
    emit("    CLC : LDA rot_b1 : ADC rot_t4 : STA rot_b1")
    emit("    LDA rot_b2 : ADC rot_t6 : STA rot_b2")
    emit(f"    BCC rot_nc{e}")
    emit("    INC rot_b3")
    emit(f".rot_nc{e}")
    emit(f"    LDA rot_s+{j}")
    emit(f".rot{e}_sign")
    emit("    EOR #0                          ; patched: the entry's sign")
    emit(f"    BPL rot_add{e}")
    emit("    LDA rot_b0 : ORA rot_b1")
    emit(f"    BEQ rot_whole{e}")
    emit("    LDA rot_b2 : EOR #&FF : STA rot_b2 : LDA rot_b3 : EOR #&FF : STA rot_b3")
    emit(f"    JMP rot_add{e}")
    emit(f".rot_whole{e}")
    emit("    LDA #0 : SEC : SBC rot_b2 : STA rot_b2 : LDA #0 : SBC rot_b3 : STA rot_b3")
    emit(f".rot_add{e}")
    emit(f"    CLC : LDA {acc} : ADC rot_b2 : STA {acc}")
    emit(f"    LDA {acc}+1 : ADC rot_b3 : STA {acc}+1")
    emit(f"    JMP {nxt(e)}")
    unit("rot", e, j, acc, nxt(e))
emit(".rot_done")
emit("    RTS")
emit()

emit("""\\ rotate_approx: rot_acc = cam rot_d from d's high bytes alone (rot_dh and
\\ rot_s from rotate_abs): each term M |d_hi| / 256, truncated.
.rotate_approx
    STZ rot_acc : STZ rot_acc+1 : STZ rot_acc+2 : STZ rot_acc+3 : STZ rot_acc+4 : STZ rot_acc+5
""")
for e in range(9):
    i, j = divmod(e, 3)
    acc = f"rot_acc+{2 * i}"
    emit(f"\\ term {e}: {'xyz'[i]}' on {'xyz'[j]}")
    emit(f".rap{e}")
    emit(f"    JMP rap{e}_mul                   ; patched as rot{e}")
    emit(f"    ZA_CANJUMP rap{e}_mul, rap{e}_unit, {anxt(e)}")
    emit(f".rap{e}_mul")
    emit(f"    LDY rot_dh+{j}")
    emit("    SEC")
    emit(f".rap{e}_a")
    emit("    LDA sqr_hi,Y")
    emit(f".rap{e}_b")
    emit("    SBC neg_hi,Y : STA rot_t1               ; M's low byte by d_hi, its high byte")
    emit("    SEC")
    emit(f".rap{e}_c")
    emit("    LDA sqr_lo,Y")
    emit(f".rap{e}_d")
    emit("    SBC neg_lo,Y : STA rot_b2")
    emit(f".rap{e}_e")
    emit("    LDA sqr_hi,Y")
    emit(f".rap{e}_f")
    emit("    SBC neg_hi,Y : STA rot_b3               ; M's high byte by d_hi")
    emit("    LDA rot_b2 : CLC : ADC rot_t1 : STA rot_b2")
    emit(f"    BCC rap_nc{e}")
    emit("    INC rot_b3")
    emit(f".rap_nc{e}")
    emit(f"    LDA rot_s+{j}")
    emit(f"    EOR rot{e}_sign+1                ; the entry's sign, as the exact term's")
    emit(f"    BPL rap_add{e}")
    emit(f"    SEC : LDA {acc} : SBC rot_b2 : STA {acc}")
    emit(f"    LDA {acc}+1 : SBC rot_b3 : STA {acc}+1")
    emit(f"    JMP {anxt(e)}")
    emit(f".rap_add{e}")
    emit(f"    CLC : LDA {acc} : ADC rot_b2 : STA {acc}")
    emit(f"    LDA {acc}+1 : ADC rot_b3 : STA {acc}+1")
    emit(f"    JMP {anxt(e)}")
    unit("rap", e, j, acc, anxt(e))
emit(".rap_done")
emit("    RTS")
print("\n".join(out))

#!/usr/bin/env python3
"""The object handlers' tables (the ST's), as Baron source, for the port.

    mkhandlers.py PRG OUT       write OUT (build/gen/handlers.6502)

PRG is the ST's AUTO/STAR.PRG. The build runs this: nothing derived from
the original is committed. The tables (docs/research/st-logic.md, "The
object handlers"):

- the handler by type (&08252, 62 longs), as handler_gate: by type, 0 if
  the ST's handler does nothing the port keeps (its no-op, &07AA0, and the
  GAME OVER types' palette bump, &0834A, which is the drawing's), else
  twice the number of the port's routine in handler_tab (from 1), with
  GATE_DRAWN or GATE_NEAR added where the routine does nothing unless the
  object is in the draw list or the near list, which object_handlers then
  tests for it (GATES);
- the two arctan tables angle_to_player reads (&13568, &1396A), each
  centred on its entry 256 and odd about it over every entry the lookup
  reaches (0-509): kept as their upper halves, H[m] = T[256 + m] for
  m = 0-253 and -T[256 - m] for m = 1-256, which the port negates below
  the centre (asserted here entry by entry). H's low bytes are a table
  (atan_a_lo, atan_b_lo); its high bytes, which never fall as m rises,
  are counted from the m where they step, as code: ATAN_A_HI_PLUS and
  the rest leave in A the high byte of H[Y - 1] (PLUS) or H[Y + 1]
  (MINUS), the entries angle_to_player reads for q = Y and q = -Y;
- by type, the gun's height (&0AF12, signed words), whether a missile's
  heading is its launcher's turned half round (&08354, kept as the &800
  to subtract, its high byte) and the laser's damage off level 1
  (&0AE5E: the same for every type, so a constant, asserted);
- by level, the missile's speed (&07FF4, signed words) and life (&08056,
  each below 256, so bytes, asserted).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import st_prg  # noqa: E402

HANDLER_TABLE, HANDLERS = 0x08252, 62
# The ST's handlers and the port's routines for them (src/logic/handlers.6502),
# but for SKIPPED's two, which the port has none for.
HANDLER_NAMES = {
    0x07AA0: "h_none", 0x07AAE: "h_silo", 0x07AC6: "h_mine", 0x07BF4: "h_fighter",
    0x07CA4: "h_wanderer", 0x07D8E: "h_neutron", 0x07DD2: "h_homing", 0x080D8: "h_tank",
    0x08174: "h_juno", 0x081AA: "h_pyramid", 0x081D6: "h_old_pyramid", 0x081F4: "h_tri",
    0x0821A: "h_type3", 0x08232: "h_beam", 0x0834A: "h_gameover",
}
# What the port leaves out, and the routines whose first test is a list's
# flag (the ST's &08174, &081AA, &081D6 and &081F4 test +23, &0821A +22).
SKIPPED = {"h_none", "h_gameover"}
GATES = {"h_juno": "GATE_NEAR", "h_pyramid": "GATE_NEAR", "h_old_pyramid": "GATE_NEAR",
         "h_tri": "GATE_NEAR", "h_type3": "GATE_DRAWN"}
GATE_BITS = {"GATE_DRAWN": 0x80, "GATE_NEAR": 0x40}
ATAN_A, ATAN_B, ATAN_ENTRIES = 0x13568, 0x1396A, 513
ATAN_REACHED = 510                      # (q + &FF) & &1FF, q in -&FF..&FE
TYPES = 30
GUN_Y, FLIP, LASER_DAMAGE = 0x0AF12, 0x08354, 0x0AE5E
SPEED, SPEED_LEVELS = 0x07FF4, 49
LIFE, LIFE_LEVELS = 0x08056, 65


def bytes_of(label, values):
    out = [f".{label}"]
    for i in range(0, len(values), 16):
        out.append("    EQUB " + ", ".join(str(v) for v in values[i:i + 16]))
    return out


def atan_half(prg, base):
    t = [prg.s16(base + 2 * i) for i in range(ATAN_ENTRIES)]
    half = [t[256 + m] for m in range(254)] + [-t[256 - m] for m in range(254, 257)]
    for m in range(1, 257):
        assert half[m] == -t[256 - m], f"arctan &{base:05X}: entry {256 - m} isn't -entry {256 + m}"
    for m in range(254):
        assert half[m] == t[256 + m]
    return half


def atan_bytes(label, half):
    """H's low bytes, and the macros that count its high bytes' steps."""
    hi = [v >> 8 for v in half]
    assert min(half) >= 0 and hi[0] == 0 and all(a <= b for a, b in zip(hi, hi[1:])), f"{label}'s high bytes aren't steps"
    steps = [m for m in range(1, len(half)) for _ in range(hi[m] - hi[m - 1])]
    assert max(steps) + 1 <= 255
    out = bytes_of(f"{label}_lo", [v & 0xFF for v in half])
    for path, shift in (("PLUS", 1), ("MINUS", -1)):
        out += [f"MACRO {label.upper()}_HI_{path}", "    LDA #0"]
        out += [f"    CPY #{m + shift} : ADC #0" for m in steps] + ["ENDMACRO"]
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    prg = st_prg.load(sys.argv[1])
    out = ["; Generated by tools/mkhandlers.py from the ST's STAR.PRG: do not edit.", ""]
    names = [HANDLER_NAMES[prg.u32(HANDLER_TABLE + 4 * t)] for t in range(HANDLERS)]
    called = sorted(set(names) - SKIPPED)
    assert 2 * len(called) < min(GATE_BITS.values())
    out += [f"HANDLER_TYPES = {HANDLERS}", "HANDLERS = {" + ", ".join(called) + "}"]
    out += [f"{g} = &{b:02X}" for g, b in GATE_BITS.items()]
    gate = [0 if n in SKIPPED else 2 * (called.index(n) + 1) + GATE_BITS.get(GATES.get(n), 0) for n in names]
    out += bytes_of("handler_gate", gate) + [".handler_tab", "    EQUW " + ", ".join(called), ""]
    out += atan_bytes("atan_a", atan_half(prg, ATAN_A)) + atan_bytes("atan_b", atan_half(prg, ATAN_B)) + [""]
    gun = [prg.s16(GUN_Y + 2 * t) for t in range(TYPES)]
    out += [f"MISSILE_TYPES = {TYPES}"]
    out += bytes_of("gun_y_lo", [g & 0xFF for g in gun]) + bytes_of("gun_y_hi", [(g >> 8) & 0xFF for g in gun])
    out += bytes_of("missile_flip", [8 if prg.u16(FLIP + 2 * t) else 0 for t in range(TYPES)])
    damage = {prg.u16(LASER_DAMAGE + 2 * t) for t in range(TYPES)}
    assert len(damage) == 1, f"the laser's damage differs by type: {sorted(damage)}"
    out += [f"LASER_DAMAGE = {damage.pop()}", ""]
    speed = [prg.s16(SPEED + 2 * n) for n in range(SPEED_LEVELS)]
    life = [prg.u16(LIFE + 2 * n) for n in range(LIFE_LEVELS)]
    assert max(life) < 256
    out += [f"SPEED_LEVELS = {SPEED_LEVELS}", f"LIFE_LEVELS = {LIFE_LEVELS}"]
    out += bytes_of("missile_speed_lo", [s & 0xFF for s in speed])
    out += bytes_of("missile_speed_hi", [(s >> 8) & 0xFF for s in speed])
    out += bytes_of("missile_life", life)
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()

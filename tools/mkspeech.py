#!/usr/bin/env python3
"""Clare Edgeley's four speech clips, from the ST's STAR.PRG, as the
SN76489 plays samples (decision 5): each clip scaled to the chip's whole
range, then each 8-bit sample the nearest of the chip's sixteen volume
levels (2dB apart, 15 silent), the error carried to the next sample,
packed two a byte (the first in the high nibble), at the ST's own rate.

    mkspeech.py PRG OUTDIR [--wav DIR]

writes OUTDIR/speech.bin (the clips one after another) and
OUTDIR/speech.6502 (each clip's offset and length in samples); --wav also
writes what the chip would play, for listening (tools/st_samples.py --wav
writes the ST's own).

The samples are the ST's .snd files, signed (docs/research/st.md,
"Samples"); a level is the volume as a fraction of full, 10^(-k/10) for k
of 0-14.
"""
import argparse
import struct
import sys
import wave
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import st_prg  # noqa: E402
import st_samples  # noqa: E402

LEVELS = [10 ** (-k / 10) for k in range(15)] + [0.0]


def quantise(pcm):
    """The clip's levels: scaled to the chip's whole range first, since the
    levels are sparse near full and a quiet clip would get mostly error."""
    s = [b ^ 0x80 for b in pcm]
    lo, hi = min(s), max(s)
    out, err = [], 0.0
    for x in s:
        want = (x - lo) / (hi - lo) + err
        k = min(range(16), key=lambda i: abs(LEVELS[i] - want))
        err = want - LEVELS[k]
        out.append(k)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("prg")
    ap.add_argument("outdir")
    ap.add_argument("--wav")
    args = ap.parse_args()
    prg = st_prg.load(args.prg)
    data, lines = bytearray(), ["\\ Generated by tools/mkspeech.py: do not edit.", ""]
    for name, addr, _, ctrl, rate_data, _ in st_samples.SAMPLES:
        if not name.startswith("clare"):
            continue
        count, _ = struct.unpack_from(">IH", prg.image, addr)
        ks = quantise(prg.image[addr + 6:addr + 6 + count])
        if len(ks) % 2:
            ks.append(15)
        lines += [f"SPEECH_{name.upper()} = {len(data)}", f"SPEECH_{name.upper()}_SAMPLES = {len(ks)}"]
        data += bytes((ks[i] << 4) | ks[i + 1] for i in range(0, len(ks), 2))
        if args.wav:
            hz = st_samples.MFP_HZ / st_samples.PRESCALE[ctrl] / rate_data
            out = Path(args.wav)
            out.mkdir(parents=True, exist_ok=True)
            with wave.open(str(out / f"{name}_sn.wav"), "wb") as w:
                w.setnchannels(1)
                w.setsampwidth(1)
                w.setframerate(round(hz))
                w.writeframes(bytes(round(LEVELS[k] * 255) for k in ks))
    lines += [f"SPEECH_BYTES = {len(data)}", ""]
    out = Path(args.outdir)
    (out / "speech.bin").write_bytes(data)
    (out / "speech.6502").write_text("\n".join(lines))
    print(f"speech: {len(data)} bytes")


if __name__ == "__main__":
    main()

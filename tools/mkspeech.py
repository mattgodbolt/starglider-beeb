#!/usr/bin/env python3
"""Clare Edgeley's four clips, from the ST's STAR.PRG, as the SN76489 plays
them (decision 5): each clip resampled by 2:3, exact from the ST's 6144Hz
to 4096Hz, its trailing near-silence cut, scaled to the chip's whole range
and each sample the nearest of the chip's sixteen levels (2dB apart, 15
silent), the error carried to the next, packed two a byte (the first in
the high nibble), and ended by SPEECH_END.

    mkspeech.py PRG SFX.JSON OUTDIR [--wav DIR]

writes OUTDIR/speech.6502 (the part of the clips the logic bank's own
first 4K holds), OUTDIR/speech_clips.6502 (each clip's start, for the
player in bank 7, then the part its window section's tail holds),
OUTDIR/speech_a.bin, speech_b.bin and speech_c.bin (the three parts), and
OUTDIR/speech.json (each clip's levels, for tools/speechcheck.mjs). The clips run one after another
through the areas, A, B, then C, crossing from one to the next where it
fills: A from &8008 (past the bank's ROM header, zeros), B from the effects'
tables' end (SFX.JSON's bytes) to ANDY's top, C the rest. --wav also
writes what the levels say, for listening (tools/st_samples.py --wav
writes the ST's own).

The cut is the trailing run within TAIL of the clip's resting level, out
of 128: below the chip's step there, it plays as the quantiser's dither,
and the player holds the last level to the clip's end, which the ST's
length (sample_left) decides. A packed byte of SPEECH_END in a clip is
made one level louder in its second sample, so that only the end is it.
"""
import argparse
import json
import struct
import sys
import wave
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import st_prg  # noqa: E402
import st_samples  # noqa: E402

LEVELS = [10 ** (-k / 10) for k in range(15)] + [0.0]
RATE = 4096
TAIL = 4
SPEECH_END = 0xFF
ANDY_TOP = 0x9000
AREA_A = 0x8008                         # bank 7's first 4K, past the ROM header's zeros
AREA_A_BYTES = ANDY_TOP - AREA_A
LOGIC_DATA = 0x8008                     # the logic bank's: the effects' tables first


def resample(x):
    """2:3: doubled with zeros, low-passed at the new rate's Nyquist by a
    windowed sinc, every third kept."""
    up = np.zeros(len(x) * 2)
    up[::2] = x * 2
    taps = np.arange(-96, 97)
    fc = 0.95 / 6
    h = 2 * fc * np.sinc(2 * fc * taps) * np.blackman(len(taps))
    return np.convolve(up, h, mode="same")[::3]


def quantise(x):
    """The clip's levels: scaled to the chip's whole range first, since the
    levels are sparse near full and a quiet clip would get mostly error."""
    lo, hi = float(x.min()), float(x.max())
    out, err = [], 0.0
    for v in x:
        want = (v - lo) / (hi - lo) + err
        k = min(range(16), key=lambda i: abs(LEVELS[i] - want))
        err = want - LEVELS[k]
        out.append(k)
    return out


def clip(prg, addr):
    count, _ = struct.unpack_from(">IH", prg.image, addr)
    pcm = np.array([b - 256 if b >= 128 else b for b in prg.image[addr + 6:addr + 6 + count]], float)
    y = resample(pcm)
    rest = np.median(y)
    loud = np.nonzero(np.abs(y - rest) > TAIL)[0]
    ks = quantise(y)[:loud[-1] + 1]
    if len(ks) % 2:
        ks.append(ks[-1])
    packed, louder = bytearray(), 0
    for i in range(0, len(ks), 2):
        b = (ks[i] << 4) | ks[i + 1]
        if b == SPEECH_END:
            b, ks[i + 1], louder = b - 1, ks[i + 1] - 1, louder + 1
        packed.append(b)
    return ks, bytes(packed) + bytes([SPEECH_END]), len(y), louder


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("prg")
    ap.add_argument("sfx")
    ap.add_argument("outdir")
    ap.add_argument("--wav")
    args = ap.parse_args()
    prg = st_prg.load(args.prg)
    clips = []
    for name, addr, played, ctrl, data, _ in st_samples.SAMPLES:
        if name.startswith("clare"):
            assert st_samples.MFP_HZ / st_samples.PRESCALE[ctrl] / data == RATE * 3 / 2
            ks, packed, whole, louder = clip(prg, addr)
            clips.append({"name": name, "levels": ks, "bytes": packed, "played": played,
                          "whole": whole, "louder": louder})
    stream = b"".join(c["bytes"] for c in clips)
    area_b = ANDY_TOP - (LOGIC_DATA + json.loads(Path(args.sfx).read_text())["bytes"])
    assert len(stream) > AREA_A_BYTES + area_b, "the clips don't reach area C: the player's crossing wants it"
    parts = [stream[:AREA_A_BYTES], stream[AREA_A_BYTES:AREA_A_BYTES + area_b], stream[AREA_A_BYTES + area_b:]]
    starts = ["SPEECH_A", "speech_b", "speech_c"]
    head = ["\\ Generated by tools/mkspeech.py from the ST's STAR.PRG: do not edit.", ""]
    lines = head + [f"ASSERT SPEECH_A = &{AREA_A:04X} AND SPEECH_END = &{SPEECH_END:02X}",
                    f"ASSERT SPEECH_RATE = {RATE}",
                    ".speech_b", '    INCBIN "speech_b.bin"', "ASSERT P% = ANDY_TOP"]
    table = head + ["\\ by clip (sample_clip, from 1): &80 if it starts in the logic bank's",
                    "\\ area, and its address", ".speech_far"]
    at, area_of, addr_of = 0, [], []
    for c in clips:
        area = 0 if at < AREA_A_BYTES else 1 if at < AREA_A_BYTES + area_b else 2
        off = at - [0, AREA_A_BYTES, AREA_A_BYTES + area_b][area]
        area_of.append(area)
        addr_of.append(f"{starts[area]} + {off}")
        c.update(area=area, offset=off)
        at += len(c["bytes"])
    table += ["    EQUB " + ", ".join("&80" if a == 1 else "0" for a in area_of),
              ".speech_lo", "    EQUB " + ", ".join(f"LO({a})" for a in addr_of),
              ".speech_hi", "    EQUB " + ", ".join(f"HI({a})" for a in addr_of),
              ".speech_c", '    INCBIN "speech_c.bin"']
    out = Path(args.outdir)
    (out / "speech_a.bin").write_bytes(parts[0])
    (out / "speech_b.bin").write_bytes(parts[1])
    (out / "speech_c.bin").write_bytes(parts[2])
    (out / "speech.6502").write_text("\n".join(lines) + "\n")
    (out / "speech_clips.6502").write_text("\n".join(table) + "\n")
    (out / "speech.json").write_text(json.dumps({
        "rate": RATE, "end": SPEECH_END, "parts": [len(p) for p in parts],
        "clips": [{k: v for k, v in c.items() if k != "bytes"} for c in clips]}) + "\n")
    if args.wav:
        wav = Path(args.wav)
        wav.mkdir(parents=True, exist_ok=True)
        for c in clips:
            with wave.open(str(wav / f"{c['name']}_levels.wav"), "wb") as w:
                w.setnchannels(1)
                w.setsampwidth(1)
                w.setframerate(RATE)
                w.writeframes(bytes(round(LEVELS[k] * 255) for k in c["levels"]))
    print(f"speech: {len(stream)} bytes, {[len(p) for p in parts]} by area; "
          f"{sum(c['whole'] - len(c['levels']) for c in clips)} samples cut; "
          f"{sum(c['louder'] for c in clips)} bytes made unlike the end")


if __name__ == "__main__":
    main()

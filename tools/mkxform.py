#!/usr/bin/env python3
"""Generate the vertex transforms (Baron source), for drawing only
(decision 1: approximate where it only draws).

    mkxform.py > build/gen/xform.6502

Both take a vertex's byte coordinates k (as u = k + 128, xf_u) by a matrix
of words, each object's, whose magnitudes and signs are patched into the
code:

- xform: into camera space, x' = (A k) / 1024 + t, where A is the object's
  matrix scaled to its shape (A = m x g / 256, xf_amag and xf_asign,
  render.6502), three rows, summed into px, xf_y and pz; render.6502's
  vertex adds t, or its fold put 4t in the starting values and patched
  xform_back to say so;
- screen: straight onto the screen, for an object far enough away that
  its perspective is linear across it (render.6502, decision 10): two rows
  of B, the first-order change in x' and y' on the screen, sc_bmag and
  sc_bsign, from the object's centre on the screen (sc_x0q, sc_y0q).

Each object, the setup patches the matrix's bytes into the quarter-square
reads of the terms, and each term's sign into how it's added: EORed with
&00 or &FF and added with the carry clear or set, as subtracting is adding
the complement and one. Taking u = k + 128 makes every product unsigned; the 128 comes
off once an object, as the accumulators' starting values (-A/2 summed
along each row). The low byte of each product is dropped, so a term is
A u / 256 to within one, and a sum is in quarters of a unit.
"""

out = []


def emit(s=""):
    out.append(s)


emit("""\\ Generated by tools/mkxform.py: do not edit.

ZA_AUTO 3, xf_u             ; a vertex's coordinates, k + 128
ZA_AUTO1 xf_plo

CLC_OP = &18
SEC_OP = &38
CARRY_BIT = CLC_OP EOR SEC_OP   ; a sign's mask AND this, OR CLC_OP: CLC or SEC
BRA_OP = &80
LDA_IMM = &A9                   ; a BRA made LDA #, to carry on instead
""")


def row_start(i, start, origin, ones=False):
    """The row's starting value from its sum (sum, 24 bits), and with ones,
    plus ones (signed) for the ones its terms add."""
    emit("    LDA sum+2 : CMP #&80 : ROR A : ROR sum+1 : ROR sum")
    if ones:
        assert not origin
        emit(f"    \\ row {i} starts at ones - (the row's sum) / 2")
        emit(f"    LDY #0 : LDA ones : BPL ones_pos{i}")
        emit("    DEY")
        emit(f".ones_pos{i}")
        emit(f"    SEC : SBC sum : STA {start}+{2 * i}")
        emit(f"    TYA : SBC sum+1 : STA {start}+{2 * i + 1}")
    elif origin:
        emit(f"    \\ row {i} starts at {origin[i]} - (the row's sum) / 2")
        emit(f"    LDA {origin[i]} : SEC : SBC sum : STA {start}+{2 * i}")
        emit(f"    LDA {origin[i]}+1 : SBC sum+1 : STA {start}+{2 * i + 1}")
    else:
        emit(f"    \\ row {i} starts at -(the row's sum) / 2")
        emit(f"    LDA #0 : SEC : SBC sum : STA {start}+{2 * i}")
        emit(f"    LDA #0 : SBC sum+1 : STA {start}+{2 * i + 1}")


def lookups(prefix, e, mag):
    """Patch term e's quarter-square reads with its magnitude's bytes."""
    t = f"{prefix}{e}"
    emit(f"    LDA {mag}+{2 * e} : STA {t}_a+1 : EOR #&FF : STA {t}_b+1")
    emit(f"    LDA {mag}+{2 * e + 1} : STA {t}_c+1 : STA {t}_e+1 : EOR #&FF : STA {t}_d+1 : STA {t}_f+1")


def sums_loop(rows, mag, sign, start, origin, skip_zero):
    """Each row's sum of its terms' signed magnitudes (sum), made in a loop,
    and so its starting value; each term's sign (bit 7) widened in place to
    a mask, &00 or &FF, as nothing reads it after. With skip_zero, a term
    whose magnitude is zero is left out, and the one each other term adds
    counted (ones)."""
    for i in range(rows):
        ix = "{" + ", ".join(str(2 * e) for e in range(3 * i, 3 * i + 3)) + "}"
        iy = f"{3 * i}..{3 * i + 2}"
        emit("    STZ sum : STZ sum+1 : STZ sum+2" + (" : STZ ones" if skip_zero else ""))
        emit(f"    LDX #{6 * i} : LDY #{3 * i}")
        emit(f".sum{i}")
        if skip_zero:
            emit(f"    LDA {mag},X : ZA_INDEXEDBY {ix}")
            emit(f"    ORA {mag}+1,X : ZA_INDEXEDBY {ix}")
            emit(f"    BEQ next{i}")
        emit(f"    LDA {sign},Y : ZA_INDEXEDBY {iy}")
        emit(f"    BMI neg{i}")
        emit(f"    CLC : LDA sum : ADC {mag},X : ZA_INDEXEDBY {ix}")
        emit(f"    STA sum : LDA sum+1 : ADC {mag}+1,X : ZA_INDEXEDBY {ix}")
        emit(f"    STA sum+1 : BCC pos{i}")
        emit("    INC sum+2")
        emit(f".pos{i}")
        if skip_zero:
            emit("    DEC ones")
        emit(f"    BRA next{i}")
        emit(f".neg{i}")
        emit(f"    LDA #&FF : STA {sign},Y : ZA_INDEXEDBY {iy}")
        emit(f"    SEC : LDA sum : SBC {mag},X : ZA_INDEXEDBY {ix}")
        emit(f"    STA sum : LDA sum+1 : SBC {mag}+1,X : ZA_INDEXEDBY {ix}")
        emit(f"    STA sum+1 : BCS neg_c{i}")
        emit("    DEC sum+2")
        emit(f".neg_c{i}")
        if skip_zero:
            emit("    INC ones")
        emit(f".next{i}")
        emit(f"    INX : INX : INY : CPY #{3 * i + 3} : BNE sum{i}")
        row_start(i, start, origin, skip_zero)


def signs(t, e, sign):
    """Patch term e's sign, from its mask (sums_loop's)."""
    emit(f"    LDA {sign}+{e} : STA {t}_m0+1 : STA {t}_m1+1 : AND #CARRY_BIT : ORA #CLC_OP : STA {t}_c0")


def setup_skipping(name, prefix, rows, mag, sign, start):
    """name_setup for name_vertex with each term's skip: a term whose
    magnitude is zero adds nothing, and is skipped (and if it's the first
    of its row, the row's starting value is copied instead)."""
    n = 3 * rows
    emit(f"""\\ {name}_setup: specialise {name}_vertex to the object's {mag} and
\\ {sign} (by term: {rows} rows of x, y, z), skipping the terms that are zero.
.{name}_setup
{{
    ZA_AUTO 3, sum
    ZA_AUTO1 ones                       ; the ones the row's terms add, negated""")
    sums_loop(rows, mag, sign, start, None, True)
    for e in range(n):
        t = f"{prefix}{e}"
        i, j = divmod(e, 3)
        emit(f"    \\ term {e}")
        emit(f"    LDA {mag}+{2 * e} : ORA {mag}+{2 * e + 1} : BEQ zero{e}")
        lookups(prefix, e, mag)
        signs(t, e, sign)
        emit(f"    LDA #LDA_IMM : STA {t}_k")
        if j == 0:
            emit(f"    LDA #BRA_OP : STA {prefix}row{i}_k")
        emit(f"    BRA done{e}")
        emit(f".zero{e}")
        emit(f"    LDA #BRA_OP : STA {t}_k")
        if j == 0:
            emit(f"    LDA #LDA_IMM : STA {prefix}row{i}_k")
        emit(f".done{e}")
    emit("    RTS")
    emit("}")
    emit()


def setup_choosing(name, prefix, prefix8, rows, mag, sign, start, origin, call):
    """name_setup, compact: the rows' sums in a loop, each term's sign made a
    mask; then the terms patched into name_vertex, or into name8_vertex
    if every magnitude's high byte is zero, and the call site set to it."""
    n = 3 * rows
    emit(f"""\\ {name}_setup: specialise {name}_vertex to the object's {mag} and
\\ {sign} (by term: {rows} rows of x, y, z), or {name}8_vertex if every
\\ term's high byte is zero; {call} jumps to whichever.
.{name}_setup
{{
    ZA_AUTO 3, sum""")
    sums_loop(rows, mag, sign, start, origin, False)
    emit("    LDA " + " : ORA ".join(f"{mag}+{2 * e + 1}" for e in range(n)) + " : BEQ bytes")
    emit("    JMP words")
    emit(".bytes")
    emit(f"    LDA #LO({name}8_vertex) : STA {call}+1 : LDA #HI({name}8_vertex) : STA {call}+2")
    for e in range(n):
        t = f"{prefix8}{e}"
        emit(f"    \\ term {e}")
        if e % 3:
            emit(f"    LDA {mag}+{2 * e} : BEQ zero{e}")
            emit(f"    STA {t}_a+1 : EOR #&FF : STA {t}_b+1")
            signs(t, e, sign)
            emit(f"    LDA #LDA_IMM : STA {t}_k")
            emit(f"    BRA done{e}")
            emit(f".zero{e}")
            emit(f"    LDA #BRA_OP : STA {t}_k")
            emit(f".done{e}")
        else:
            emit(f"    LDA {mag}+{2 * e} : STA {t}_a+1 : EOR #&FF : STA {t}_b+1")
            signs(t, e, sign)
    emit("    RTS")
    emit(".words")
    emit(f"    LDA #LO({name}_vertex) : STA {call}+1 : LDA #HI({name}_vertex) : STA {call}+2")
    for e in range(n):
        t = f"{prefix}{e}"
        emit(f"    \\ term {e}")
        lookups(prefix, e, mag)
        signs(t, e, sign)
    emit("    RTS")
    emit("}")
    emit()


def row_sum(acc, i):
    """Row i's sum: acc, a word a row, or a name for each row."""
    return acc[i] if isinstance(acc, (list, tuple)) else f"{acc}+{2 * i}"


def vertex(name, prefix, rows, acc, start, back, skipping=False, backs=None):
    """With backs, the jump back is patched (name_back), to back or one of
    backs."""
    sums_named = ", ".join(row_sum(acc, i) for i in range(rows))
    emit(f"\\ {name}_vertex: {sums_named} = the matrix by (xf_u - 128), / 256. A term is the")
    emit("\\ high byte by u (X:xf_plo) and the low byte by u, its high byte, added in")
    if skipping:
        emit("\\ A with the carry the SBC leaves, one (the setup takes them off the")
        emit("\\ starting values); the first column's terms add to the starting values.")
        emit("\\ A term that's zero is skipped (its _k a BRA, or else LDA #), and if it's")
        emit("\\ the first of its row, the row's starting value copied (the row's _k).")
    else:
        emit("\\ A; the first column's terms add to the starting values.")
    if backs:
        emit(f"\\ Its one caller jumps here, and it jumps back to {back} or {', '.join(backs)}")
        emit(f"\\ ({name}_back, patched).")
    else:
        emit(f"\\ Its one caller jumps here, and it jumps back to {back}.")
    emit(f".{name}_vertex")
    if skipping:
        # Every row's first term that's done writes the row, so the sums'
        # old values are dead here, whatever skips Baron can see.
        emit(f"    ZA_DISCARD {acc if isinstance(acc, str) else sums_named}")
        for i in range(rows):
            r = f"{prefix}row{i}"
            a = row_sum(acc, i)
            emit(f".{r}_k")
            emit(f"    BRA {r}_go                            ; patched: BRA, or LDA # to copy")
            emit(f"    ZA_CANJUMP {r}_go, {r}_copy")
            emit(f".{r}_copy")
            emit(f"    LDA {start}+{2 * i} : STA {a} : LDA {start}+{2 * i + 1} : STA {a}+1")
            emit(f".{r}_go")
    for j in range(3):
        emit(f"    LDY xf_u+{j}")
        for i in range(rows):
            e = 3 * i + j
            t = f"{prefix}{e}"
            a = row_sum(acc, i)
            src = f"{start}+{2 * i}" if j == 0 else a
            emit(f"    \\ term {e}: row {i} on {'xyz'[j]}")
            if skipping:
                emit(f".{t}_k")
                emit(f"    BRA {t}_end                           ; patched: BRA if it's zero, or LDA #")
                emit(f"    ZA_CANJUMP {t}_end, {t}_go")
                emit(f".{t}_go")
            emit("    SEC")
            emit(f".{t}_c")
            emit("    LDA sqr_lo,Y")
            emit(f".{t}_d")
            emit("    SBC neg_lo,Y : STA xf_plo")
            emit(f".{t}_e")
            emit("    LDA sqr_hi,Y")
            emit(f".{t}_f")
            emit("    SBC neg_hi,Y : TAX                     ; (C = 1: a product isn't negative)")
            emit(f".{t}_a")
            emit("    LDA sqr_hi,Y")
            emit(f".{t}_b")
            emit("    SBC neg_hi,Y")
            emit("    ADC xf_plo" if skipping else "    CLC : ADC xf_plo")
            emit(f"    BCC {t}_nc")
            emit("    INX")
            emit(f".{t}_nc")
            emit(f".{t}_m0")
            emit("    EOR #0                                ; patched: the sign, &00 or &FF ...")
            emit(f".{t}_c0")
            emit("    CLC                                   ; ... and the carry in, CLC or SEC")
            emit(f"    ADC {src} : STA {a}")
            emit("    TXA")
            emit(f".{t}_m1")
            emit("    EOR #0                                ; patched: the sign")
            emit(f"    ADC {src}+1 : STA {a}+1")
            if skipping:
                emit(f".{t}_end")
    if backs:
        emit(f".{name}_back")
        emit(f"    JMP {back}                            ; patched")
        emit(f"    ZA_CANJUMP {', '.join([back] + backs)}")
    else:
        emit(f"    JMP {back}")
    emit()


def vertex8(name, prefix, rows, acc, start, back):
    emit(f"\\ {name}8_vertex: {name}_vertex for a matrix whose high bytes are zero, so")
    emit(f"\\ a term is the low byte by u, its high byte, alone; back to {back}.")
    emit("\\ Past the first column, a term that's zero is skipped (its _k a BRA).")
    emit(f".{name}8_vertex")
    for j in range(3):
        emit(f"    LDY xf_u+{j}")
        for i in range(rows):
            e = 3 * i + j
            t = f"{prefix}{e}"
            a = f"{acc}+{2 * i}"
            src = f"{start}+{2 * i}" if j == 0 else a
            emit(f"    \\ term {e}: row {i} on {'xyz'[j]}")
            if j:
                emit(f".{t}_k")
                emit(f"    BRA {t}_end                           ; patched: BRA if it's zero, or LDA #")
                emit(f"    ZA_CANJUMP {t}_end, {t}_go")
                emit(f".{t}_go")
            emit("    SEC")
            emit(f".{t}_a")
            emit("    LDA sqr_hi,Y")
            emit(f".{t}_b")
            emit("    SBC neg_hi,Y")
            emit(f".{t}_m0")
            emit("    EOR #0                                ; patched: the sign, &00 or &FF ...")
            emit(f".{t}_c0")
            emit("    CLC                                   ; ... and the carry in, CLC or SEC")
            emit(f"    ADC {src} : STA {a}")
            emit(f"    LDA {src}+1")
            emit(f".{t}_m1")
            emit("    ADC #0                                ; patched: the sign")
            emit(f"    STA {a}+1")
            if j:
                emit(f".{t}_end")
    emit(f"    JMP {back}")
    emit()


def sums(rows, acc, start, what):
    emit(f"ZA_AUTO {2 * rows}, {acc}             ; {what}, in quarters")
    emit(f"ZA_AUTO {2 * rows}, {start}           ; their starting values")
    emit()


# The xform's sums are x', y' and z' in quarters of a world unit: x' and z'
# are the projection's px and pz (render.6502), which vertex shifts in
# place into world units.
emit("ZA_AUTO2 xf_y                 ; y', in quarters (x' and z' are px and pz)")
emit("ZA_AUTO 6, xf_start           ; their starting values")
emit()
setup_skipping("xform", "xf", 3, "xf_amag", "xf_asign", "xf_start")
vertex("xform", "xf", 3, ["px", "xf_y", "pz"], "xf_start", "vertex.back", skipping=True,
       backs=["vertex.folded"])
sums(2, "sc_acc", "sc_start", "the screen's x and y")
setup_choosing("screen", "sc", "s8", 2, "sc_bmag", "sc_bsign", "sc_start", ["sc_x0q", "sc_y0q"],
               "vertex_far.screen")
vertex("screen", "sc", 2, "sc_acc", "sc_start", "vertex_far.back")
vertex8("screen", "s8", 2, "sc_acc", "sc_start", "vertex_far.back")
print("\n".join(out))

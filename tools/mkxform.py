#!/usr/bin/env python3
"""Generate the vertex transform (Baron source): a shape's vertex into
camera space, for drawing only (decision 1: approximate where it only
draws).

    mkxform.py > build/gen/xform.6502

The object's matrix is scaled to its shape (A = m x g / 256, xf_amag and
xf_asign, render.6502) so a vertex's byte coordinates k give camera space
directly: x' = (A k) / 1024 + t. Each object, xform_setup patches A's
bytes into the quarter-square reads of xform_vertex's nine terms, and each
term's sign into whether it adds or subtracts. The coordinates are taken
as u = k + 128, which makes every product unsigned; the 128 comes off once
an object, as the accumulators' starting values (-A/2 summed along each
row). The low byte of each product is dropped, so a term is A u / 256 to
within one, and the sum, in quarters of a world unit, is shifted down to
world units.
"""

out = []


def emit(s=""):
    out.append(s)


emit("""\\ Generated by tools/mkxform.py: do not edit.

ZA_AUTO 6, xf_acc           ; x', y', z' in quarters of a world unit
ZA_AUTO 6, xf_start         ; their starting values, xform_setup's
ZA_AUTO1 xf_t, xf_plo, xf_phi

ADC_ZP = &65
SBC_ZP = &E5
CLC_OP = &18
SEC_OP = &38

\\ xform_setup: specialise xform_vertex to the object's xf_amag and
\\ xf_asign (by term, rows x', y', z' of x, y, z).
.xform_setup
{
    ZA_AUTO 3, sum
""")
for i in range(3):
    emit(f"    STZ sum : STZ sum+1 : STZ sum+2")
    for j in range(3):
        e = 3 * i + j
        emit(f"    \\ term {e}")
        emit(f"    LDA xf_amag+{2 * e} : STA xf{e}_a+1 : EOR #&FF : STA xf{e}_b+1")
        emit(f"    LDA xf_amag+{2 * e + 1} : STA xf{e}_c+1 : STA xf{e}_e+1 : EOR #&FF : STA xf{e}_d+1 : STA xf{e}_f+1")
        emit(f"    LDA xf_asign+{e} : BMI neg{e}")
        emit(f"    LDA #CLC_OP : STA xf{e}_op1 : LDA #ADC_ZP : STA xf{e}_op2 : STA xf{e}_op3")
        emit(f"    CLC : LDA sum : ADC xf_amag+{2 * e} : STA sum")
        emit(f"    LDA sum+1 : ADC xf_amag+{2 * e + 1} : STA sum+1")
        emit(f"    LDA sum+2 : ADC #0 : STA sum+2")
        emit(f"    JMP done{e}")
        emit(f".neg{e}")
        emit(f"    LDA #SEC_OP : STA xf{e}_op1 : LDA #SBC_ZP : STA xf{e}_op2 : STA xf{e}_op3")
        emit(f"    SEC : LDA sum : SBC xf_amag+{2 * e} : STA sum")
        emit(f"    LDA sum+1 : SBC xf_amag+{2 * e + 1} : STA sum+1")
        emit(f"    LDA sum+2 : SBC #0 : STA sum+2")
        emit(f".done{e}")
    emit(f"    \\ row {i} starts at -(the row's sum) / 2")
    emit("    LDA sum+2 : CMP #&80 : ROR A : ROR sum+1 : ROR sum")
    emit(f"    LDA #0 : SEC : SBC sum : STA xf_start+{2 * i}")
    emit(f"    LDA #0 : SBC sum+1 : STA xf_start+{2 * i + 1}")
emit("    RTS")
emit("}")
emit()
emit("""\\ xform_vertex: xf_acc = A (u - 128) / 256, for the coordinates xf_u
\\ (k + 128, x y z).
ZA_AUTO 3, xf_u
.xform_vertex
    LDA xf_start : STA xf_acc : LDA xf_start+1 : STA xf_acc+1
    LDA xf_start+2 : STA xf_acc+2 : LDA xf_start+3 : STA xf_acc+3
    LDA xf_start+4 : STA xf_acc+4 : LDA xf_start+5 : STA xf_acc+5
""")
for j in range(3):
    emit(f"    LDY xf_u+{j}")
    for i in range(3):
        e = 3 * i + j
        acc = f"xf_acc+{2 * i}"
        emit(f"    \\ term {e}: {'xyz'[i]}' on {'xyz'[j]}")
        emit("    SEC")
        emit(f".xf{e}_a")
        emit("    LDA sqr_hi,Y")
        emit(f".xf{e}_b")
        emit("    SBC neg_hi,Y : STA xf_t                ; A's low byte by u, its high byte")
        emit("    SEC")
        emit(f".xf{e}_c")
        emit("    LDA sqr_lo,Y")
        emit(f".xf{e}_d")
        emit("    SBC neg_lo,Y : STA xf_plo")
        emit(f".xf{e}_e")
        emit("    LDA sqr_hi,Y")
        emit(f".xf{e}_f")
        emit("    SBC neg_hi,Y : STA xf_phi              ; A's high byte by u")
        emit("    LDA xf_plo : CLC : ADC xf_t : STA xf_plo")
        emit(f"    BCC xf_nc{e}")
        emit("    INC xf_phi")
        emit(f".xf_nc{e}")
        emit(f".xf{e}_op1")
        emit("    CLC                                   ; patched: CLC or SEC")
        emit(f"    LDA {acc}")
        emit(f".xf{e}_op2")
        emit("    ADC xf_plo                            ; patched: ADC or SBC")
        emit(f"    STA {acc}")
        emit(f"    LDA {acc}+1")
        emit(f".xf{e}_op3")
        emit("    ADC xf_phi                            ; patched: ADC or SBC")
        emit(f"    STA {acc}+1")
emit("    RTS")
print("\n".join(out))

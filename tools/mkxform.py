#!/usr/bin/env python3
"""Generate the vertex transforms (Baron source), for drawing only
(decision 1: approximate where it only draws).

    mkxform.py > build/gen/xform.6502

Both take a vertex's byte coordinates k (as u = k + 128, xf_u) by a matrix
of words, each object's, whose magnitudes and signs are patched into the
code:

- xform: into camera space, x' = (A k) / 1024 + t, where A is the object's
  matrix scaled to its shape (A = m x g / 256, xf_amag and xf_asign,
  render.6502), three rows;
- screen: straight onto the screen, for an object far enough away that
  its perspective is linear across it (render.6502, decision 10): two rows
  of B, the first-order change in x' and y' on the screen, sc_bmag and
  sc_bsign.

Each object, the setup patches the matrix's bytes into the quarter-square
reads of the terms, and each term's sign into whether it adds or
subtracts. Taking u = k + 128 makes every product unsigned; the 128 comes
off once an object, as the accumulators' starting values (-A/2 summed
along each row). The low byte of each product is dropped, so a term is
A u / 256 to within one, and a sum is in quarters of a unit.
"""

out = []


def emit(s=""):
    out.append(s)


emit("""\\ Generated by tools/mkxform.py: do not edit.

ZA_AUTO 3, xf_u             ; a vertex's coordinates, k + 128
ZA_AUTO1 xf_t, xf_plo, xf_phi

ADC_ZP = &65
SBC_ZP = &E5
CLC_OP = &18
SEC_OP = &38
""")


def transform(name, prefix, rows, mag, sign, acc, start, what):
    emit(f"""ZA_AUTO {2 * rows}, {acc}             ; {what}, in quarters
ZA_AUTO {2 * rows}, {start}           ; their starting values, {name}_setup's

\\ {name}_setup: specialise {name}_vertex to the object's {mag} and
\\ {sign} (by term: {rows} rows of x, y, z).
.{name}_setup
{{
    ZA_AUTO 3, sum
""")
    for i in range(rows):
        emit("    STZ sum : STZ sum+1 : STZ sum+2")
        for j in range(3):
            e = 3 * i + j
            t = f"{prefix}{e}"
            emit(f"    \\ term {e}")
            emit(f"    LDA {mag}+{2 * e} : STA {t}_a+1 : EOR #&FF : STA {t}_b+1")
            emit(f"    LDA {mag}+{2 * e + 1} : STA {t}_c+1 : STA {t}_e+1 : EOR #&FF : STA {t}_d+1 : STA {t}_f+1")
            emit(f"    LDA {sign}+{e} : BMI neg{e}")
            emit(f"    LDA #CLC_OP : STA {t}_op1 : LDA #ADC_ZP : STA {t}_op2 : STA {t}_op3")
            emit(f"    CLC : LDA sum : ADC {mag}+{2 * e} : STA sum")
            emit(f"    LDA sum+1 : ADC {mag}+{2 * e + 1} : STA sum+1")
            emit("    LDA sum+2 : ADC #0 : STA sum+2")
            emit(f"    JMP done{e}")
            emit(f".neg{e}")
            emit(f"    LDA #SEC_OP : STA {t}_op1 : LDA #SBC_ZP : STA {t}_op2 : STA {t}_op3")
            emit(f"    SEC : LDA sum : SBC {mag}+{2 * e} : STA sum")
            emit(f"    LDA sum+1 : SBC {mag}+{2 * e + 1} : STA sum+1")
            emit("    LDA sum+2 : SBC #0 : STA sum+2")
            emit(f".done{e}")
        emit(f"    \\ row {i} starts at -(the row's sum) / 2")
        emit("    LDA sum+2 : CMP #&80 : ROR A : ROR sum+1 : ROR sum")
        emit(f"    LDA #0 : SEC : SBC sum : STA {start}+{2 * i}")
        emit(f"    LDA #0 : SBC sum+1 : STA {start}+{2 * i + 1}")
    emit("    RTS")
    emit("}")
    emit()
    emit(f"\\ {name}_vertex: {acc} = the matrix by (xf_u - 128), / 256.")
    emit(f".{name}_vertex")
    for i in range(rows):
        emit(f"    LDA {start}+{2 * i} : STA {acc}+{2 * i} : LDA {start}+{2 * i + 1} : STA {acc}+{2 * i + 1}")
    for j in range(3):
        emit(f"    LDY xf_u+{j}")
        for i in range(rows):
            e = 3 * i + j
            t = f"{prefix}{e}"
            a = f"{acc}+{2 * i}"
            emit(f"    \\ term {e}: row {i} on {'xyz'[j]}")
            emit("    SEC")
            emit(f".{t}_a")
            emit("    LDA sqr_hi,Y")
            emit(f".{t}_b")
            emit("    SBC neg_hi,Y : STA xf_t                ; the low byte by u, its high byte")
            emit("    SEC")
            emit(f".{t}_c")
            emit("    LDA sqr_lo,Y")
            emit(f".{t}_d")
            emit("    SBC neg_lo,Y : STA xf_plo")
            emit(f".{t}_e")
            emit("    LDA sqr_hi,Y")
            emit(f".{t}_f")
            emit("    SBC neg_hi,Y : STA xf_phi              ; the high byte by u")
            emit("    LDA xf_plo : CLC : ADC xf_t : STA xf_plo")
            emit(f"    BCC {t}_nc")
            emit("    INC xf_phi")
            emit(f".{t}_nc")
            emit(f".{t}_op1")
            emit("    CLC                                   ; patched: CLC or SEC")
            emit(f"    LDA {a}")
            emit(f".{t}_op2")
            emit("    ADC xf_plo                            ; patched: ADC or SBC")
            emit(f"    STA {a}")
            emit(f"    LDA {a}+1")
            emit(f".{t}_op3")
            emit("    ADC xf_phi                            ; patched: ADC or SBC")
            emit(f"    STA {a}+1")
    emit("    RTS")
    emit()


transform("xform", "xf", 3, "xf_amag", "xf_asign", "xf_acc", "xf_start", "x', y', z' in world units")
transform("screen", "sc", 2, "sc_bmag", "sc_bsign", "sc_acc", "sc_start", "the screen's x and y")
print("\n".join(out))

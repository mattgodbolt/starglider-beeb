#!/usr/bin/env python3
"""Interrogate's data (src/interrogate.6502), from the ST's STAR.PRG: the
start of the DOCKED file, which lies over the missile view's window
picture in bank 7 while the player is docked (src/docked.6502).

    mkinterrogate.py PRG OUT.6502 OUT.json

The ST's Interrogate (read_keys' &02A44, docs/research/st-logic.md) shows
entries 1 to 17 of its tables in turn: each a type (&02B98, words) and
three strings (&02BBC, &02C04 and &02C4C, pointers: two lines of
description and a name), with its prompt (&02B74) above. It prints them
through print_at_a0 (&0112E) in the colour the code sets before each:
font_colour's opaque 8 x 8 cells (docs/research/st-panel.md).

This writes them as the panel's printer has its own (tools/mkpanel.py):

- the types, a byte an entry, and each entry's three strings' addresses;
- the strings as glyph numbers, ended by &FF, then the prompt;
- the glyphs of the characters they use, 16 bytes each, MODE 1's for
  colour 3 (mkpanel.py's glyph_bytes), a char the ST draws as another's
  sharing its glyph;
- where each string goes (the ST's colour-mode screen offsets, which the
  code picks when $2BC is set) and its colour.

OUT.json holds the same for the checks (tools/dockcheck.mjs).
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mkpanel  # noqa: E402
import st_prg  # noqa: E402

TYPES = 0x02B98                         # 18 words, entry 0 unused
LINE1, LINE2, NAME = 0x02BBC, 0x02C04, 0x02C4C  # 18 pointers each
PROMPT = 0x02B74
ENTRIES = 17
STRINGS = ("name", "line1", "line2")
# Each string's place (the colour screen offset, &02ABA-&02B20) and colour
# (the move.b #c, D_019F0 before its print), with the instruction that has
# each, to be read back.
PLACES = {
    "line1": (0x02AC0, 0x02AC4),        # adda.w #$4109 / move.b #2
    "line2": (0x02AE2, None),           # adda.w #$4749 (line 1's colour left)
    "name": (0x02AFC, 0x02B00),         # adda.w #$dd9 / move.b #3
    "prompt": (0x02B20, 0x02B24),       # adda.w #$789 / move.b #1
}


def cstr(prg, a):
    out = []
    while prg.u8(a + len(out)):
        out.append(prg.u8(a + len(out)))
    return out


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    prg = st_prg.load(sys.argv[1])
    types = [prg.u16(TYPES + 2 * i) for i in range(ENTRIES + 1)]
    assert types[0] == 0 and all(0 < t < 32 for t in types[1:])
    entries = []
    for i in range(1, ENTRIES + 1):
        entries.append({
            "type": types[i],
            "name": cstr(prg, prg.u32(NAME + 4 * i)),
            "line1": cstr(prg, prg.u32(LINE1 + 4 * i)),
            "line2": cstr(prg, prg.u32(LINE2 + 4 * i)),
        })
    prompt = cstr(prg, PROMPT)
    places, colour = {}, None
    for k, (adda, move) in PLACES.items():
        assert prg.u16(adda) == 0xD0FC, f"{k}: not adda.w"
        places[k] = mkpanel.st_xy(prg.u16(adda + 2))
        if move is not None:
            assert prg.u16(move) == 0x13FC and prg.u32(move + 4) == 0x19F0, f"{k}: not the colour's move"
            colour = prg.u16(move + 2)
        places[k] = places[k] + (colour,)
    # the glyphs, in order of first use, the space first
    chars = [" "]
    for s in [prompt] + [e[k] for e in entries for k in STRINGS]:
        for b in s:
            assert mkpanel.FONT_FIRST <= b <= mkpanel.FONT_LAST, f"char &{b:02X} isn't in the font"
            if chr(b) not in chars:
                chars.append(chr(b))
    glyph, kept = {}, []
    for ch in chars:
        b = mkpanel.glyph_bytes(prg, ch)
        same = [k for k, c in enumerate(kept) if mkpanel.glyph_bytes(prg, c) == b]
        glyph[ch] = same[0] if same else len(kept)
        if not same:
            kept.append(ch)
    assert len(kept) < 0xFF
    g = lambda s: [glyph[chr(b)] for b in s] + [0xFF]

    L = ["\\ Generated by tools/mkinterrogate.py from the ST's STAR.PRG: do not edit.", ""]
    L.append(f"INT_ENTRIES = {ENTRIES}")
    L.append(f"INT_GLYPH_SPACE = {glyph[' ']}")
    for k, (x, y, c) in places.items():
        L += [f"INT_{k.upper()}_X = {x}", f"INT_{k.upper()}_Y = {y}", f"INT_{k.upper()}_COLOUR = {c}"]
    L.append("")
    L.append("\\ by entry, the first first: its type, and its strings' addresses")
    L.append(".int_types")
    L.append("    EQUB " + ", ".join(str(e["type"]) for e in entries))
    for k in STRINGS:
        for half in ("LO", "HI"):
            L.append(f".int_{k}_{half.lower()}")
            L.append("    EQUB " + ", ".join(f"{half}(int_{k}_{i + 1})" for i in range(ENTRIES)))
    L.append("")
    L.append("\\ the strings, as glyph numbers, ended by &FF")
    for i, e in enumerate(entries):
        for k in STRINGS:
            text = bytes(e[k]).decode("latin1")
            L.append(f".int_{k}_{i + 1}   ; {text!r}")
            L.append("    EQUB " + ", ".join(f"&{b:02X}" for b in g(e[k])))
    L.append(f".int_prompt   ; {bytes(prompt).decode('latin1')!r}")
    L.append("    EQUB " + ", ".join(f"&{b:02X}" for b in g(prompt)))
    L.append("")
    L.append("\\ the glyphs: 16 bytes each (tools/mkpanel.py's)")
    L.append(".int_font")
    for ch in kept:
        L.append("    EQUB " + ", ".join(f"&{b:02X}" for b in mkpanel.glyph_bytes(prg, ch)) + f"  ; {ch!r}")
    Path(sys.argv[2]).write_text("\n".join(L) + "\n")
    Path(sys.argv[3]).write_text(json.dumps({
        "entries": [{k: (v if k == "type" else bytes(v).decode("latin1")) for k, v in e.items()} for e in entries],
        "prompt": bytes(prompt).decode("latin1"),
        "places": {k: list(v) for k, v in places.items()},
        "font": {ch: mkpanel.glyph_bytes(prg, ch) for ch in chars},
    }))


if __name__ == "__main__":
    main()

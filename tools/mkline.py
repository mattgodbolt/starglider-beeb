#!/usr/bin/env python3
"""Generate the port's line drawer (Baron source) for MODE 1 at 320 x 200.

    mkline.py > build/gen/line.6502

The routine follows tools/beeb_line_m1.py (Nick Jameson's MODE 4 design
moved to 2 bits a pixel), changed for the ST's geometry and look:

- a character row is 640 bytes (MODE 1's full 80 columns), so a row step
  is a 16-bit subtraction, and x has 9 bits (0-319);
- pixels are ORed in, as the ST's are (decision 2), and `line_erase`
  patches every write to store a zero instead, so the same routine
  erases a line by clearing each byte it touched;
- a shallow line more than 255 pixels across is drawn as two halves, as
  the Bresenham error is a byte.

As in beeb_line_m1.py: one unrolled block per pixel position (four to a
byte), dx and dy patched into each block, the error in A with the carry
kept set, shallow runs gathered in X and written once a byte-row, and only
minor-axis steps counted. Lines are drawn upwards (y0 >= y1 after a swap),
so a row step is DEY. Both end points are lit. It needs the 65C12.

The caller sets line_x0 (two bytes), line_y0, line_x1 (two bytes) and
line_y1 in zero page, every coordinate on the screen, and the colour with
set_colour. `screen_row_lo/hi` (screen.6502) give each character row's
address.
"""

PIX = [0x88, 0x44, 0x22, 0x11]  # one pixel at position p (0 = leftmost)
RF = [0xFF, 0x77, 0x33, 0x11]  # pixels p..3
LT = [0x88, 0xCC, 0xEE, 0xFF]  # pixels 0..p

out = []
writes = []  # labels of every ORA (scr),Y, which line_erase patches


def emit(s=""):
    out.append(s)


def write(label):
    """The read-modify-write of a pixel run: OR it in (or, erasing, store 0)."""
    writes.append(label)
    emit(f".{label}")
    emit("    ORA (line_scr),Y : STA (line_scr),Y")




emit("""\\ Generated by tools/mkline.py: do not edit.

\\ line: draw (line_x0, line_y0) to (line_x1, line_y1) in the colour
\\ set_colour set last. Every coordinate must be on the screen.
.line
{
    LDA line_x1 : SEC : SBC line_x0 : TAX
    LDA line_x1+1 : SBC line_x0+1
    BPL positive
    EOR #&FF : TAY : TXA : EOR #&FF : CLC : ADC #1 : TYA : ADC #0
.positive
    BEQ line_short                          ; |dx| < 256
    \\ More than a byte across: two halves, meeting at the middle.
    LDA line_x0 : CLC : ADC line_x1 : STA line_mx
    LDA line_x0+1 : ADC line_x1+1 : LSR A : ROR line_mx : STA line_mx+1
    LDA line_y0 : CLC : ADC line_y1 : ROR A : STA line_my
    LDA line_x1 : PHA : LDA line_x1+1 : PHA : LDA line_y1 : PHA
    LDA line_mx : STA line_x1 : LDA line_mx+1 : STA line_x1+1 : LDA line_my : STA line_y1
    JSR line_short
    PLA : STA line_y1 : PLA : STA line_x1+1 : PLA : STA line_x1
    LDA line_mx : STA line_x0 : LDA line_mx+1 : STA line_x0+1 : LDA line_my : STA line_y0
}
.line_short
    LDA line_y0 : SEC : SBC line_y1 : BCS dyok
    LDX line_x0 : LDY line_x1 : STY line_x0 : STX line_x1  ; draw upwards: swap the ends
    LDX line_x0+1 : LDY line_x1+1 : STY line_x0+1 : STX line_x1+1
    LDX line_y0 : LDY line_y1 : STY line_y0 : STX line_y1
    EOR #&FF : ADC #1                      ; C = 0 from the borrow
.dyok
    STA line_dy
    \\ The byte: the character row's address plus 8 a byte column.
    LDA line_y0 : LSR A : LSR A : LSR A : TAX
    LDA line_x0 : AND #&FC : ASL A : STA line_scr  ; C = bit 7 of x
    LDA line_x0+1 : ROL A : TAY
    LDA line_scr : ADC screen_row_lo,X : STA line_scr  ; C = 0 from the ROL
    TYA : ADC screen_row_hi,X : STA line_scr+1
    LDA line_y0 : AND #7 : TAY
    LDA line_x0 : AND #3 : ASL A : TAX     ; entry block * 2
    LDA line_x1 : SEC : SBC line_x0 : STA line_dx
    LDA line_x1+1 : SBC line_x0+1
    LDA line_dx
    BCS rightward
    EOR #&FF : ADC #1                      ; |dx|, C = 0 from the borrow
    CMP line_dy : BCC steep_l : BEQ steep_l : JMP shallow_l
.rightward
    CMP line_dy : BCC steep_r : BEQ steep_r : JMP shallow_r
""")

# ---- set-up for each variant ------------------------------------------------
for v, kind in (("tr", "steep_r"), ("tl", "steep_l"), ("sr", "shallow_r"), ("sl", "shallow_l")):
    steep = v[0] == "t"
    emit(f".{kind}")
    emit("    STA line_dx")
    if steep:
        emit("    CMP #0                          ; STA set no flags")
        emit(f"    BEQ {v}_single")
        for p in range(4):
            emit(f"    STA {v}_sbc{p}+1")
        emit("    STA line_cnt")
        emit("    LDA #2 : STA line_ls")
        emit("    LDA line_dy")
        for p in range(4):
            emit(f"    STA {v}_adc{p}+1")
        emit("    LSR A : STA line_errs")
        emit(f"    SEC : JMP ({v}_entry,X)")
        emit(f"    ZA_CANJUMP {v}_s0, {v}_s1, {v}_s2, {v}_s3")
        emit(f".{v}_single                       ; vertical: one virtual step after dy rows")
        emit("    LDA #1")
        for p in range(4):
            emit(f"    STA {v}_sbc{p}+1")
        emit("    STA line_cnt : STA line_ls")
        emit(f"    LDA line_dy : SEC : JMP ({v}_entry,X)")
        emit(f"    ZA_CANJUMP {v}_s0, {v}_s1, {v}_s2, {v}_s3")
    else:
        for p in range(4):
            emit(f"    STA {v}_adc{p}+1")
        emit("    LDA line_dy")
        emit(f"    BEQ {v}_single")
        for p in range(4):
            emit(f"    STA {v}_sbc{p}+1")
        emit("    STA line_cnt")
        emit("    LDA #2 : STA line_ls")
        emit("    LDA line_dx : LSR A : STA line_errs")
        emit(f"    SEC : JMP ({v}_entry,X)")
        emit(f"    ZA_CANJUMP {v}_s0, {v}_s1, {v}_s2, {v}_s3")
        emit(f".{v}_single                       ; horizontal: one virtual step after dx pixels")
        emit("    LDA #1")
        for p in range(4):
            emit(f"    STA {v}_sbc{p}+1")
        emit("    STA line_cnt : STA line_ls")
        emit(f"    LDA line_dx : SEC : JMP ({v}_entry,X)")
        emit(f"    ZA_CANJUMP {v}_s0, {v}_s1, {v}_s2, {v}_s3")
    emit()

# ---- steep blocks ------------------------------------------------------------
# A block's exits (a row step, the last step) are on whichever side of the
# blocks keeps every branch in range: the first two blocks' before them,
# the last two's after.
def steep_exits(v, p, done):
    emit(f".{v}_row{p}                           ; up a character row; X = the error")
    emit(f"    JSR line_row_up : TXA : SEC : LDY #7 : BRA {v}_t{p}")
    emit(f".{v}_e{p}                             ; the last x-step, or the virtual one")
    emit("    DEC line_ls")
    emit(f"    BEQ {done}")
    emit("    SBC line_errs : INC line_cnt")
    emit(f"    BCS {v}_x{p}")
    emit(f"    BRA {done}                   ; the end-run trick failed")


for v, order, step in (("tr", [0, 1, 2, 3], +1), ("tl", [3, 2, 1, 0], -1)):
    emit(f"\\ ---- steep, {'right' if step > 0 else 'left'}wards ----")
    emit(f".{v}_done0")
    emit("    RTS")
    for p in order[:2]:
        steep_exits(v, p, f"{v}_done0")
    for i, p in enumerate(order):
        last = i == 3
        emit(f".{v}_s{p}")
        emit("    TAX")
        emit(f".{v}_s{p}x")
        emit(f".{v}_m{p}")
        emit(f"    LDA #&{PIX[p]:02X}                    ; colour & pixel {p}, patched")
        write(f"{v}_w{p}")
        emit("    TXA")
        emit("    DEY")
        emit(f"    BMI {v}_row{p}")
        emit(f".{v}_t{p}")
        emit(f".{v}_sbc{p}")
        emit("    SBC #0                          ; dx, patched")
        emit(f"    BCS {v}_s{p}")
        emit(f".{v}_adc{p}")
        emit("    ADC #0                          ; dy, patched; C = 1 after")
        emit("    DEC line_cnt")
        emit(f"    BEQ {v}_e{p}")
        emit(f".{v}_x{p}")
        if last:
            # next byte: column +8 (rightwards) or -8 (leftwards), C = 1 here
            emit("    TAX")
            emit("    LDA line_scr")
            if step > 0:
                emit("    ADC #7 : STA line_scr")
                emit(f"    BCC {v}_col_ok")
                emit("    INC line_scr+1")
            else:
                emit("    SBC #8 : STA line_scr")
                emit(f"    BCS {v}_col_ok")
                emit("    DEC line_scr+1")
            emit(f".{v}_col_ok")
            emit("    TXA : SEC")
            emit(f"    BRA {v}_s{order[0]}x")
    for p in order[2:]:
        steep_exits(v, p, f"{v}_done")
    emit(f".{v}_done")
    emit("    RTS")
    emit(f".{v}_entry")
    emit("    EQUW " + ", ".join(f"{v}_s{p}" for p in range(4)))
    emit()

# ---- shallow blocks ----------------------------------------------------------
# A pixel with no y-step costs SBC + BCS. X holds the run mask from the pixel
# the run started at; a y-step trims it at this pixel and writes the byte.
def shallow_exits(v, p, done):
    emit(f".{v}_row{p}                           ; up a character row; A and X are free")
    emit(f"    JSR line_row_up : SEC : LDY #7 : BRA {v}_g{p}")
    emit(f".{v}_e{p}")
    emit("    DEC line_ls")
    emit(f"    BEQ {done}")
    emit("    LDA line_err : SBC line_errs : STA line_err : INC line_cnt")
    emit(f"    BCS {v}_f{p}")
    emit(f"    BRA {done}                   ; the end-run trick failed")


for v, order, step in (("sr", [0, 1, 2, 3], +1), ("sl", [3, 2, 1, 0], -1)):
    emit(f"\\ ---- shallow, {'right' if step > 0 else 'left'}wards ----")
    start_mask = RF if step > 0 else LT
    trim_mask = LT if step > 0 else RF
    emit(f".{v}_done0")
    emit("    RTS")
    for p in order[:2]:
        shallow_exits(v, p, f"{v}_done0")
    for i, p in enumerate(order):
        last = i == 3
        nxt = order[i + 1] if not last else None
        emit(f".{v}_s{p}")
        emit(f".{v}_a{p}")
        emit(f"    LDX #&{start_mask[p]:02X}                    ; colour & run from pixel {p}, patched")
        emit(f".{v}_b{p}")
        emit(f".{v}_sbc{p}")
        emit("    SBC #0                          ; dy, patched")
        emit(f"    BCS {v}_b{nxt}" if not last else f"    BCS {v}_byte")
        emit(f".{v}_adc{p}")
        emit("    ADC #0                          ; dx, patched; C = 1 after")
        emit("    STA line_err")
        emit("    TXA")
        if trim_mask[p] != 0xFF:
            emit(f"    AND #&{trim_mask[p]:02X}")
        write(f"{v}_w{p}")
        emit("    DEC line_cnt")
        emit(f"    BEQ {v}_e{p}")
        emit(f".{v}_f{p}")
        emit("    DEY")
        emit(f"    BMI {v}_row{p}")
        emit(f".{v}_g{p}")
        if not last:
            emit("    LDA line_err")  # falls into the next block's run start
        else:
            emit(f"    BRA {v}_next")
    emit(f".{v}_byte                             ; end of a byte with no y-step: C = 1")
    emit("    STA line_err")
    emit("    TXA")
    write(f"{v}_wb")
    emit(f".{v}_next")
    emit("    LDA line_scr")
    if step > 0:
        emit("    ADC #7 : STA line_scr             ; C = 1 on every path here: +8")
        emit(f"    BCC {v}_col_ok")
        emit("    INC line_scr+1")
    else:
        emit("    SBC #8 : STA line_scr             ; C = 1 on every path here")
        emit(f"    BCS {v}_col_ok")
        emit("    DEC line_scr+1")
    emit(f".{v}_col_ok")
    emit(f"    LDA line_err : SEC")
    emit(f"    JMP {v}_a{order[0]}")
    for p in order[2:]:
        shallow_exits(v, p, f"{v}_done")
    emit(f".{v}_done")
    emit("    RTS")
    emit(f".{v}_entry")
    emit("    EQUW " + ", ".join(f"{v}_s{p}" for p in range(4)))
    emit()

emit("\\ line_row_up: up a character row (640 bytes); A is lost.")
emit(".line_row_up")
emit("    LDA line_scr : SEC : SBC #LO(SCREEN_ROW) : STA line_scr")
emit("    LDA line_scr+1 : SBC #HI(SCREEN_ROW) : STA line_scr+1")
emit("    RTS")
emit()

# ---- colour and mode ---------------------------------------------------------
emit("\\ set_colour: A = the colour's byte (&0F, &F0 or &FF for colours 1-3).")
emit(".set_colour")
emit("    TAX")
for p in range(4):
    emit(f"    TXA : AND #&{PIX[p]:02X} : STA tr_m{p}+1 : STA tl_m{p}+1")
    emit(f"    TXA : AND #&{RF[p]:02X} : STA sr_a{p}+1")
    emit(f"    TXA : AND #&{LT[p]:02X} : STA sl_a{p}+1")
emit("    RTS")
emit()
emit("\\ line_draw and line_erase: ORA (line_scr),Y in every write, or AND #0,")
emit("\\ which stores a zero over the byte.")
emit(".line_draw")
emit("    LDA #&11 : LDX #line_scr                ; ORA (zp),Y")
emit("    BRA line_mode")
emit(".line_erase")
emit("    LDA #&29 : LDX #0                       ; AND #0")
emit(".line_mode")
for w in writes:
    emit(f"    STA {w} : STX {w}+1")
emit("    RTS")
print("\n".join(out))

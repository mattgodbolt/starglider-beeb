#!/usr/bin/env python3
"""Generate the port's line drawer (Baron source) for MODE 1 at 320 x 200.

    mkline.py build/gen

writes line.6502, the drawer, and linemode.6502, line_draw and
line_erase, which switch its writes and can go in another section.

The routine follows tools/beeb_line_m1.py (Nick Jameson's MODE 4 design
moved to 2 bits a pixel), changed for the ST's geometry and look:

- a character row is 640 bytes (MODE 1's full 80 columns), so a row step
  is a 16-bit subtraction, and x has 9 bits (0-319);
- pixels are ORed in, as the ST's are (decision 2), and `line_erase`
  patches every write to store a zero instead, so the same routine
  erases a line by clearing each byte it touched;
- a shallow line more than 255 pixels across is drawn as two halves, as
  the Bresenham error is a byte.

As in beeb_line_m1.py: one unrolled block per pixel position (four to a
byte), the minor axis's length patched into each block (the major's is
read from zero page, as only a minor step adds it), the error in A with
the carry kept set, shallow runs gathered in X and written once a
byte-row, and only minor-axis steps counted. Lines are drawn upwards from
the lower end, so a row step is DEY. Both end points are lit. It needs
the 65C12.

`line_plot` sets a line up (its first byte's address, its row in the
character row, |dx|, dy and its block), logs the set-up on the erase
list and draws it; `line_go` draws a line set up, so erasing one from the
list (hazel.6502's erase_screen) skips the set-up. The caller sets
line_x0 (two bytes), line_y0, line_x1 (two bytes) and line_y1 in zero
page, every coordinate on the screen, and the colour with set_colour.
`screen_row_lo/hi` (hazel.6502) give each character row's address.
"""

import sys
from pathlib import Path

PIX = [0x88, 0x44, 0x22, 0x11]  # one pixel at position p (0 = leftmost)
RF = [0xFF, 0x77, 0x33, 0x11]  # pixels p..3
LT = [0x88, 0xCC, 0xEE, 0xFF]  # pixels 0..p

# The four kinds of line, in the order of line_go's code: a line's code is
# its kind * 8 + its first pixel's position * 2.
KINDS = (("tr", "steep_r"), ("tl", "steep_l"), ("sr", "shallow_r"), ("sl", "shallow_l"))

out = []
writes = []  # labels of every ORA (scr),Y, which line_erase patches


def emit(s=""):
    out.append(s)


def write(label):
    """The read-modify-write of a pixel run: OR it in (or, erasing, store 0)."""
    writes.append(label)
    emit(f".{label}")
    emit("    ORA (line_scr),Y : STA (line_scr),Y")


def row_up():
    """Up a character row (640 bytes): A is lost, and C = 1 after, as the
    line is on the screen."""
    emit("    LDA line_scr : SEC : SBC #LO(SCREEN_ROW) : STA line_scr")
    emit("    LDA line_scr+1 : SBC #HI(SCREEN_ROW) : STA line_scr+1")


def field(name):
    """A field of the erase list, on the first screen's page: draw_phase
    moves it to the screen drawn (memory.6502)."""
    return f"ERASE_LIST + EF_{name} * 512"


def start(e):
    """line_plot's set-up of a line drawn upwards from end e, the lower:
    A = dy, X the erase list's index; Y is left the row in the character
    row, A dx's high byte and C its sign. Each end has its own, so the
    ends aren't swapped, and its own stores into the erase list."""
    x, y, xo = f"line_x{e}", f"line_y{e}", f"line_x{1 - e}"
    return f"""    \\ Upwards from (line_x{e}, line_y{e}). The byte: the character row's
    \\ address plus 8 a byte column.
    STA line_dy
.f_dy{e}
    STA {field("DY")},X
    LDA {y} : LSR A : LSR A : LSR A : TAY
    LDA {x} : AND #&FC : ASL A : STA line_scr  ; C = bit 7 of x
    LDA {x}+1 : ROL A : STA line_scr+1         ; C = 0
    LDA line_scr : ADC screen_row_lo,Y : STA line_scr
.f_lo{e}
    STA {field("LO")},X
    LDA line_scr+1 : ADC screen_row_hi,Y : STA line_scr+1
.f_hi{e}
    STA {field("HI")},X
    LDA {y} : AND #7 : TAY
.f_row{e}
    STA {field("ROW")},X
    LDA {x} : AND #3 : ASL A : STA code        ; the first pixel's block * 2
    LDA {xo} : SEC : SBC {x} : STA line_dx
    LDA {xo}+1 : SBC {x}+1"""


emit(f"""\\ Generated by tools/mkline.py: do not edit.

\\ line_plot: (line_x0, line_y0) to (line_x1, line_y1) in the colour
\\ set_colour set last, into the screen draw_bank names (0 for main RAM's,
\\ ACCCON_X for shadow RAM's), and its set-up onto that screen's erase list
\\ at erase_i, which counts down (memory.6502); with the list full, onto
\\ index 0, which is never read. Every coordinate must be on the screen.
\\ X is set from the start, for the erase list, and stays set to draw into
\\ shadow RAM: it moves every access to &3000-&7FFF, code's too, so this
\\ runs from HAZEL and reads only zero page and HAZEL while it's set.
ZA_AUTO1 erase_i
.line_plot
{{
    ZA_AUTO1 code
    LDA #ACCCON_X : TSB acccon
    LDX erase_i
    LDA line_y0 : SEC : SBC line_y1 : BCC up
    BEQ flat
.down
{start(0)}
    BRA across
.flat                                       ; a row: drawn from its left end
    LDA line_x0 : CMP line_x1 : LDA line_x0+1 : SBC line_x1+1
    LDA #0 : BCC down
    CLC                                     ; so dy stays 0
.up
    EOR #&FF : ADC #1                      ; C = 0 from the borrow
{start(1)}
.across                                     ; A = dx's high byte, C = 0 if dx < 0
    BCC leftward
    BNE wide                                ; 256 or more across
    LDA line_dx : CMP line_dy : BCC kind : BEQ kind  ; steep rightwards: kind 0
    LDA #2 * 8 : TSB code              ; shallow rightwards
    BRA kind
.leftward
    CMP #&FF : BNE wide
    LDA line_dx : EOR #&FF : ADC #0 : BEQ wide  ; |dx|, C = 1 from the CMP
    STA line_dx
    CMP line_dy : BCC left_steep : BEQ left_steep
    LDA #3 * 8 : TSB code              ; shallow leftwards
    BRA kind
.left_steep
    LDA #1 * 8 : TSB code
.kind
    LDA line_dx
.f_dx
    STA {field("DX")},X
    LDA code
.f_code
    STA {field("CODE")},X
    TXA : BEQ logged                        ; full: the overflow stays on index 0
    DEX : STX erase_i
.logged
    LDX code
    LDA draw_bank : BNE shadow
    LDA #ACCCON_X : TRB acccon
    JMP (line_setups,X)
    ZA_CANJUMP {", ".join(k for _, k in KINDS)}
.shadow
    JSR line_go
    LDA #ACCCON_X : TRB acccon
    RTS
.wide
    \\ More than a byte across: two halves, meeting at the middle, each a
    \\ line of its own on the list. The far end and the middle wait on the
    \\ stack, so nothing in zero page is held across the first half.
    LDA line_x1 : PHA : LDA line_x1+1 : PHA : LDA line_y1 : PHA
    LDA line_x0 : CLC : ADC line_x1 : TAY
    LDA line_x0+1 : ADC line_x1+1 : LSR A : STA line_x1+1 : PHA
    TYA : ROR A : STA line_x1
    LDA line_y0 : CLC : ADC line_y1 : ROR A : STA line_y1
    LDY line_x1 : PHY : PHA
    JSR line_plot
    PLA : STA line_y0 : PLA : STA line_x0 : PLA : STA line_x0+1
    PLA : STA line_y1 : PLA : STA line_x1+1 : PLA : STA line_x1
    JMP line_plot
}}

\\ line_go: a line set up drawn: its first byte's character row and column
\\ in line_scr, Y its row in the character row, X its code (kind * 8 +
\\ block * 2), line_dx = |dx| and line_dy = dy, both under 256.
.line_go
    JMP (line_setups,X)
    ZA_CANJUMP {", ".join(k for _, k in KINDS)}
.line_setups
    EQUW {", ".join(k for _, k in KINDS for _p in range(4))}
.line_entries
    EQUW {", ".join(f"{v}_s{p}" for v, _ in KINDS for p in range(4))}
""")

# ---- set-up for each variant ------------------------------------------------
# A steep line steps a row each pixel and x on the minor axis; a shallow
# one the other way. The minor axis's length is patched into every block's
# SBC and counted; the major's is the ADC's (zero page: it's read only on
# a minor step). A minor axis of length 0 is a column or a row, which
# line_plot makes rightwards (a row from its left end): it can't be a
# leftward kind's.
for v, kind in KINDS:
    steep = v[0] == "t"
    major, minor = ("line_dy", "line_dx") if steep else ("line_dx", "line_dy")
    emit(f".{kind}")
    emit(f"    LDA {minor}")
    if v[1] == "r":
        emit(f"    BEQ {v}_single")
    for p in range(4):
        emit(f"    STA {v}_sbc{p}+1")
    emit("    STA line_cnt")
    emit("    LDA #2 : STA line_ls")
    emit(f"    LDA {major} : LSR A : STA line_errs")
    emit("    SEC : JMP (line_entries,X)")
    emit(f"    ZA_CANJUMP {v}_s0, {v}_s1, {v}_s2, {v}_s3")
    emit()

emit("""\\ A column (and a dot): dy + 1 rows of the pixel at block X / 2.
.tr_single
    LDA line_pix,X : AND set_colour+1 : STA tv_m+1
    LDX line_dy : INX
.tv_m
    LDA #0                          ; colour & pixel, patched""")
write("tv_w")
emit("""    DEX : BEQ tv_done
    DEY : BPL tv_m""")
row_up()
emit("""    LDY #7 : BRA tv_m
.tv_done
    RTS
.line_pix                           ; each block's pixel, by block * 2
    EQUB &88, 0, &44, 0, &22, 0, &11

\\ A row: dx + 1 pixels rightwards from block (X - 16) / 2, its bytes
\\ drawn (sr_row) or, erasing, zeroed (sr_row_erase): line_draw and
\\ line_erase patch the JMP, so sr_row's writes are only ever ORs.
.sr_single
    JMP sr_row
    ZA_CANJUMP sr_row, sr_row_erase
.sr_row
    TXA : LSR A : AND #3 : TAX              ; the first pixel's position, C = 0
    ADC line_dx : STA line_err              ; the last's from the first byte's left, C its bit 8
    ROR A : LSR A : STA line_cnt            ; the bytes after the first
    LDA line_rf,X : AND set_colour+1        ; the first byte: pixels p..3
    LDX line_cnt : BEQ sr_one
    ORA (line_scr),Y : STA (line_scr),Y
.sr_right
    LDA line_scr : CLC : ADC #8 : STA line_scr
    BCC sr_col
    INC line_scr+1
.sr_col
    DEX : BEQ sr_last
    LDA set_colour+1                        ; a whole byte
    ORA (line_scr),Y : STA (line_scr),Y
    BRA sr_right
.sr_one                                     ; first and last in one byte
    STA line_cnt
    LDA line_err : AND #3 : TAX
    LDA line_lt,X : AND line_cnt
    BRA sr_end
.sr_last
    LDA line_err : AND #3 : TAX
    LDA line_lt,X : AND set_colour+1        ; the last byte: pixels 0..its own
.sr_end
    ORA (line_scr),Y : STA (line_scr),Y
    RTS
.line_lt                                    ; pixels 0..p, then (line_rf) p..3
    EQUB &88, &CC, &EE
line_rf = P%
    EQUB &FF, &77, &33, &11
.sr_row_erase
    TXA : LSR A : AND #3 : ADC line_dx      ; the last pixel: C = 0 from the LSR, and after it bit 8
    ROR A : LSR A : TAX : INX               ; the bytes
.sr_zero
    LDA #0 : STA (line_scr),Y
    LDA line_scr : CLC : ADC #8 : STA line_scr
    BCC sr_zeroed
    INC line_scr+1
.sr_zeroed
    DEX : BNE sr_zero
    RTS
""")

# ---- steep blocks ------------------------------------------------------------
# A block's exits (a row step, the last step) are on whichever side of the
# blocks keeps every branch in range: the first two blocks' before them,
# the last two's after.
def steep_exits(v, p, done):
    # A steep line steps up a row every 8 pixels, so its step is inline.
    emit(f".{v}_row{p}                           ; up a character row; X = the error")
    row_up()
    emit(f"    TXA : LDY #7 : BRA {v}_t{p}")
    emit(f".{v}_e{p}                             ; the last x-step, or the virtual one")
    emit("    DEC line_ls")
    emit(f"    BEQ {done}")
    emit("    SBC line_errs : INC line_cnt")
    emit(f"    BCS {v}_x{p}")
    emit(f"    BRA {done}                   ; the end-run trick failed")


for v, order, step in (("tr", [0, 1, 2, 3], +1), ("tl", [3, 2, 1, 0], -1)):
    emit(f"\\ ---- steep, {'right' if step > 0 else 'left'}wards ----")
    emit(f".{v}_done0")
    emit("    RTS")
    for p in order[:2]:
        steep_exits(v, p, f"{v}_done0")
    for i, p in enumerate(order):
        last = i == 3
        emit(f".{v}_s{p}")
        emit("    TAX")
        emit(f".{v}_s{p}x")
        emit(f".{v}_m{p}")
        emit(f"    LDA #&{PIX[p]:02X}                    ; colour & pixel {p}, patched")
        write(f"{v}_w{p}")
        emit("    TXA")
        emit("    DEY")
        emit(f"    BMI {v}_row{p}")
        emit(f".{v}_t{p}")
        emit(f".{v}_sbc{p}")
        emit("    SBC #0                          ; dx, patched")
        emit(f"    BCS {v}_s{p}")
        emit("    ADC line_dy                     ; C = 1 after")
        emit("    DEC line_cnt")
        emit(f"    BEQ {v}_e{p}")
        emit(f".{v}_x{p}")
        if last:
            # next byte: column +8 (rightwards) or -8 (leftwards), C = 1 here
            emit("    TAX")
            emit("    LDA line_scr")
            if step > 0:
                emit("    ADC #7 : STA line_scr")
                emit(f"    BCC {v}_col_ok")
                emit("    INC line_scr+1")
            else:
                emit("    SBC #8 : STA line_scr")
                emit(f"    BCS {v}_col_ok")
                emit("    DEC line_scr+1")
            emit(f".{v}_col_ok")
            emit("    TXA : SEC")
            emit(f"    BRA {v}_s{order[0]}x")
    for p in order[2:]:
        steep_exits(v, p, f"{v}_done")
    emit(f".{v}_done")
    emit("    RTS")
    emit()

# ---- shallow blocks ----------------------------------------------------------
# A pixel with no y-step costs SBC + BCS. X holds the run mask from the pixel
# the run started at; a y-step trims it at this pixel and writes the byte.
def shallow_exits(v, p, done):
    emit(f".{v}_row{p}                           ; up a character row; A and X are free")
    emit(f"    JSR line_row_up : LDY #7 : BRA {v}_g{p}")
    emit(f".{v}_e{p}")
    emit("    DEC line_ls")
    emit(f"    BEQ {done}")
    emit("    LDA line_err : SBC line_errs : STA line_err : INC line_cnt")
    emit(f"    BCS {v}_f{p}")
    emit(f"    BRA {done}                   ; the end-run trick failed")


for v, order, step in (("sr", [0, 1, 2, 3], +1), ("sl", [3, 2, 1, 0], -1)):
    emit(f"\\ ---- shallow, {'right' if step > 0 else 'left'}wards ----")
    start_mask = RF if step > 0 else LT
    trim_mask = LT if step > 0 else RF
    emit(f".{v}_done0")
    emit("    RTS")
    for p in order[:2]:
        shallow_exits(v, p, f"{v}_done0")
    # The step to the next byte sits before the first block, to fall into it.
    emit(f".{v}_byte                             ; end of a byte with no y-step: C = 1")
    emit("    STA line_err")
    emit("    TXA")
    write(f"{v}_wb")
    emit(f".{v}_next")
    emit("    LDA line_scr")
    if step > 0:
        emit("    ADC #7 : STA line_scr             ; C = 1 on every path here: +8")
        emit(f"    BCC {v}_col_ok")
        emit("    INC line_scr+1")
    else:
        emit("    SBC #8 : STA line_scr             ; C = 1 on every path here")
        emit(f"    BCS {v}_col_ok")
        emit("    DEC line_scr+1")
    emit(f".{v}_col_ok")
    emit(f"    LDA line_err : SEC")
    for i, p in enumerate(order):
        last = i == 3
        nxt = order[i + 1] if not last else None
        emit(f".{v}_s{p}")
        emit(f".{v}_a{p}")
        emit(f"    LDX #&{start_mask[p]:02X}                    ; colour & run from pixel {p}, patched")
        emit(f".{v}_b{p}")
        emit(f".{v}_sbc{p}")
        emit("    SBC #0                          ; dy, patched")
        emit(f"    BCS {v}_b{nxt}" if not last else f"    BCS {v}_byte")
        emit("    ADC line_dx                     ; C = 1 after")
        emit("    STA line_err")
        emit("    TXA")
        if trim_mask[p] != 0xFF:
            emit(f"    AND #&{trim_mask[p]:02X}")
        write(f"{v}_w{p}")
        emit("    DEC line_cnt")
        emit(f"    BEQ {v}_e{p}")
        emit(f".{v}_f{p}")
        emit("    DEY")
        emit(f"    BMI {v}_row{p}")
        emit(f".{v}_g{p}")
        if not last:
            emit("    LDA line_err")  # falls into the next block's run start
        else:
            emit(f"    BRA {v}_next")
    for p in order[2:]:
        shallow_exits(v, p, f"{v}_done")
    emit(f".{v}_done")
    emit("    RTS")
    emit()

emit("\\ line_row_up: up a character row (640 bytes); A is lost, and C = 1, as")
emit("\\ the line is on the screen.")
emit(".line_row_up")
row_up()
emit("    RTS")
emit()

# ---- colour and mode ---------------------------------------------------------
emit("\\ set_colour: A = the colour's byte (&0F, &F0 or &FF for colours 1-3). The")
emit("\\ masks are patched only when it changes: the blocks start as colour 3's.")
emit(".set_colour")
emit("    CMP #&FF : BEQ set_same                 ; the colour set last, patched")
emit("    STA set_colour+1")
emit("    TAX")
for p in range(4):
    emit(f"    TXA : AND #&{PIX[p]:02X} : STA tr_m{p}+1 : STA tl_m{p}+1")
    emit(f"    TXA : AND #&{RF[p]:02X} : STA sr_a{p}+1")
    emit(f"    TXA : AND #&{LT[p]:02X} : STA sl_a{p}+1")
emit(".set_same")
emit("    RTS")
drawer, out = out, []

# ---- the writes' mode, which needn't sit beside the drawer -------------------
emit("\\ Generated by tools/mkline.py: do not edit.")
emit()
emit("\\ line_draw and line_erase: ORA (line_scr),Y in every write of the line")
emit("\\ drawer (line.6502), or AND #0, which stores a zero over the byte.")
emit(".line_draw")
emit("    LDA #LO(sr_row) : STA sr_single+1 : LDA #HI(sr_row) : STA sr_single+2")
emit("    LDA #&11 : LDX #line_scr                ; ORA (zp),Y")
emit("    BRA line_mode")
emit(".line_erase")
emit("    LDA #LO(sr_row_erase) : STA sr_single+1 : LDA #HI(sr_row_erase) : STA sr_single+2")
emit("    LDA #&29 : LDX #0                       ; AND #0")
emit(".line_mode")
for w in writes:
    emit(f"    STA {w} : STX {w}+1")
emit("    RTS")

outdir = Path(sys.argv[1])
(outdir / "line.6502").write_text("\n".join(drawer) + "\n")
(outdir / "linemode.6502").write_text("\n".join(out) + "\n")

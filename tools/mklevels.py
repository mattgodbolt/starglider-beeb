#!/usr/bin/env python3
"""The ST's level layouts as Baron source, for the port's init_objects
(src/logic/level.6502).

    mklevels.py PRG OUTDIR      write OUTDIR/levels.6502

PRG is the ST's AUTO/STAR.PRG (tools/fat12.py takes it off the disc). The
build runs this: nothing derived from the original is committed.

The ST's level_lists (&17C88) holds a layout pointer for each level, 0 to
45; four layouts, each a run of four-word entries (type, sector x, sector
z, hit points) ending with a zero type word (docs/research/st-logic.md,
"The main loop ... init_objects"). Every word's high byte is 0, so the
port keeps each as its low byte, and each layout as four arrays a byte an
entry, indexed by the entry, the types ending with the zero:

    level_layout     each level's layout, by level (the 46 pointers)
    layout_type_lo, layout_type_hi, layout_x_lo ... layout_hits_hi
                     each layout's four arrays, by layout
    LAYOUT_TYPES     one more than the highest type in any layout
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import st_prg  # noqa: E402

LEVEL_LISTS = 0x17C88
LEVELS = 46
FIELDS = ("type", "x", "z", "hits")


def layout(prg, at):
    """The entries from `at` to its zero type word, as four-tuples."""
    out = []
    start = at
    while prg.u16(at) != 0:
        e = tuple(prg.u16(at + 2 * i) for i in range(4))
        if any(w > 0xFF for w in e):
            sys.exit(f"layout &{start:05X}: a word with a high byte, {e}: the port keeps bytes")
        out.append(e)
        at += 8
    if len(out) > 255:
        sys.exit(f"layout &{start:05X}: {len(out)} entries, more than a byte indexes")
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    prg = st_prg.load(sys.argv[1])
    outdir = Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True)
    ptrs = [prg.u32(LEVEL_LISTS + 4 * n) for n in range(LEVELS)]
    layouts = sorted(set(ptrs))
    entries = [layout(prg, at) for at in layouts]
    src = ["; Generated by tools/mklevels.py from the ST's STAR.PRG: do not edit.",
           f"LEVELS = {LEVELS}",
           f"LAYOUTS = {len(layouts)}",
           f"LAYOUT_TYPES = {max(e[0] for es in entries for e in es) + 1}",
           ".level_layout",
           "    EQUB " + ", ".join(str(layouts.index(p)) for p in ptrs)]
    for f in FIELDS:
        for half in ("lo", "hi"):
            src += [f".layout_{f}_{half}",
                    "    EQUB " + ", ".join(f"{half.upper()}(layout{n}_{f})" for n in range(len(layouts)))]
    for n, at in enumerate(layouts):
        src.append(f"\\ &{at:05X}: {len(entries[n])} entries")
        for i, f in enumerate(FIELDS):
            column = [e[i] for e in entries[n]] + ([0] if f == "type" else [])
            src.append(f".layout{n}_{f}")
            src += ["    EQUB " + ", ".join(str(v) for v in column[k:k + 32]) for k in range(0, len(column), 32)]
    (outdir / "levels.6502").write_text("\n".join(src) + "\n")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate the object table's layout (decision 13): the fields the port
uses, each an array by slot, and where each is in the ST's 64-byte
record, for the tools that translate between the two.

    mkobjects.py OUTDIR     writes OUTDIR/objects.6502 and OUTDIR/objects.json

The table holds the ST's 140 slots, then the silo's tunnel (the ST's
&1218) and its missile (&1258). A word is two arrays, its low bytes and
its high. What the renderer reads is in main RAM, below the screen; what
only the game's logic reads is in ANDY (&8000-&8FFF, paged with the logic's
banks: docs/plan.md). The fields and their meanings are
docs/research/st-logic.md's ("Every object field").

objects.json lists every field: its name, the ST's offset of it in the
record, its kind (byte; word, as two arrays; word8, a word whose high byte
is always 0, kept as its low byte; zero, a word always 0, not kept; port,
the port's own) and its arrays.
"""
import json
import sys
from pathlib import Path

SLOTS = 140 + 2
FIELDS = [  # (name, ST offset or None, kind, where, what)
    ("type", 0x00, "word8", "main", "the type; 0 is an empty slot"),
    ("flags", 0x02, "byte", "andy", "bit 7: lasers and ramming can't destroy it; 1: an enemy missile"),
    ("x", 0x04, "word", "main", "the position in the world"),
    ("y", 0x06, "word", "main", ""),
    ("z", 0x08, "word", "main", ""),
    ("pitch", 0x0A, "word", "main", "its own angles"),
    ("heading", 0x0C, "word", "main", ""),
    ("roll", 0x0E, "word", "andy", "(not drawn: the missiles spin it)"),
    ("speed", 0x10, "word", "andy", ""),
    ("timer_a", 0x14, "word", "andy", "the silo's missile-ready byte (high), a mine's bob count, a missile's life"),
    ("timer_b", 0x16, "word", "andy", "the silo's reload count, a mine's bob step, a tank's drive"),
    ("timer_c", 0x18, "word", "andy", "a mine's bob period; 1 on a tower group's own tower"),
    ("vx", 0x1C, "word", "andy", "the velocity: x and z a frame"),
    ("vy", 0x1E, "zero", "andy", "(always written 0)"),
    ("vz", 0x20, "word", "andy", ""),
    ("drawn", 0x22, "byte", "main", "&FF while in the draw list"),
    ("near", 0x23, "byte", "main", "&FF while in the near list"),
    ("exploding", 0x24, "byte", "main", ""),
    ("explosion", 0x26, "word8", "main", "the explosion's frame, 0-31"),
    ("cx", 0x28, "word", "main", "the position in camera space, as the list phase leaves it"),
    ("cy", 0x2A, "word", "main", ""),
    ("cz", 0x2C, "word", "main", ""),
    ("proof", 0x2E, "byte", "andy", "non-zero: lasers can't hurt it"),
    ("hits", 0x30, "word", "andy", "hits left"),
    ("exact", None, "port", "main", "1 if the list phase rotated it exactly this frame (decision 11)"),
]


def arrays(name, kind):
    if kind == "zero":
        return []
    if kind == "word":
        return [f"ob_{name}_lo", f"ob_{name}_hi"]
    return [f"ob_{name}"]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = Path(sys.argv[1])
    lines = [
        "\\ Generated by tools/mkobjects.py: do not edit.",
        "\\",
        "\\ The object table (decision 13): each field an array by slot, what the",
        "\\ renderer reads at the top of main RAM below the screen, what only the",
        "\\ logic reads in ANDY.",
        "",
        f"OB_SLOTS = {SLOTS}",
    ]
    for where, org in (("main", None), ("andy", "ANDY")):
        rows = [(f, n) for f in FIELDS if f[3] == where for n in arrays(f[0], f[2])]
        if where == "main":
            lines += [f"OB_ARRAYS = {len(rows)}", "OBJECTS = SCREEN - OB_SLOTS * OB_ARRAYS",
                      "SECTION Objects, org = OBJECTS, guard = SCREEN, virtual = TRUE"]
        else:
            lines += [f"OB_ANDY_ARRAYS = {len(rows)}", "ANDY_OBJECTS_END = ANDY + OB_SLOTS * OB_ANDY_ARRAYS",
                      "SECTION ObjectsAndy, org = ANDY, guard = ANDY_OBJECTS_END, virtual = TRUE"]
        for (name, off, kind, _, what), arr in rows:
            st = "the port's own" if off is None else f"the ST's +&{off:02X}"
            lines.append(f".{arr:<16} SKIP OB_SLOTS      ; {st}" + (f": {what}" if what and arr.endswith(('_lo', name)) else ""))
        lines += ["ENDSECTION", ""]
    (out / "objects.6502").write_text("\n".join(lines))
    fields = [{"name": n, "st": o, "kind": k, "where": w, "arrays": arrays(n, k)} for n, o, k, w, _ in FIELDS]
    (out / "objects.json").write_text(json.dumps({"slots": SLOTS, "fields": fields}, indent=1))


if __name__ == "__main__":
    main()

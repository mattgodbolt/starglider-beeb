#!/usr/bin/env python3
"""Generate the object table's layout (decision 13): the fields the port
uses, each an array by slot, and where each is in the ST's 64-byte
record, for the tools that translate between the two.

    mkobjects.py OUTDIR     writes OUTDIR/objects.6502 and OUTDIR/objects.json

The table holds the ST's 140 slots, then the silo's tunnel (the ST's
&1218) and its missile (&1258). A word is two arrays, its low bytes and
its high. objects.json lists every array: its name, the ST's offset of
its byte in the record as the port's tools hold it (tools/mkscene.py's
`record`, the words little-endian), or null for the port's own.

A field joins the table when the port transcribes a routine that reads
it; the ST's record is in docs/research/st.md.
"""
import json
import sys
from pathlib import Path

SLOTS = 140 + 2
FIELDS = [  # (name, ST offset or None, bytes, what)
    ("type", 0x00, 1, "the type; 0 is an empty slot (the ST's word, whose high byte is always 0)"),
    ("x", 0x04, 2, "the position in the world"),
    ("y", 0x06, 2, ""),
    ("z", 0x08, 2, ""),
    ("pitch", 0x0A, 2, "its own angles"),
    ("heading", 0x0C, 2, ""),
    ("drawn", 0x22, 1, "&FF while in the draw list"),
    ("near", 0x23, 1, "&FF while in the near list"),
    ("exploding", 0x24, 1, ""),
    ("cx", 0x28, 2, "the position in camera space, as the list phase leaves it"),
    ("cy", 0x2A, 2, ""),
    ("cz", 0x2C, 2, ""),
    ("exact", None, 1, "1 if the list phase rotated it exactly this frame (decision 11)"),
]


def arrays():
    for name, off, size, what in FIELDS:
        if size == 1:
            yield f"ob_{name}", off, what
        else:
            yield f"ob_{name}_lo", off, what
            yield f"ob_{name}_hi", None if off is None else off + 1, ""


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = Path(sys.argv[1])
    rows = list(arrays())
    lines = [
        "\\ Generated by tools/mkobjects.py: do not edit.",
        "\\",
        "\\ The object table (decision 13): each field an array by slot, at the",
        "\\ top of main RAM, below the screen.",
        "",
        f"OB_SLOTS = {SLOTS}",
        f"OB_ARRAYS = {len(rows)}",
        "OBJECTS = SCREEN - OB_SLOTS * OB_ARRAYS",
        "SECTION Objects, org = OBJECTS, guard = SCREEN, virtual = TRUE",
    ]
    for name, off, what in rows:
        where = "the port's own" if off is None else f"the ST's +&{off:02X}"
        lines.append(f".{name:<16} SKIP OB_SLOTS      ; {where}" + (f": {what}" if what else ""))
    lines += ["ENDSECTION", ""]
    (out / "objects.6502").write_text("\n".join(lines))
    (out / "objects.json").write_text(json.dumps({"slots": SLOTS, "arrays": [{"name": n, "st": o} for n, o, _ in rows]}, indent=1))


if __name__ == "__main__":
    main()

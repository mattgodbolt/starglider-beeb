#!/usr/bin/env python3
"""The tables collisions and the post-frame tests read, from the ST's
STAR.PRG, as Baron source for the logic's bank.

    mkcollide.py PRG OUTDIR     write OUTDIR/collide.6502

Each is the ST's (docs/research/st-logic.md, "The main loop" and "The
bearing, collisions"), by type, as low and high bytes:

    size_y      the ram box's half-height in camera y (&0ACF2); the half
                width in x and z is types.6502's size_z (&0ACB6)
    ram_score   a ram's (or the player's missile's) kill score, BCD (&0AED6)
    ram_cost    the shields a ram costs: the four tables at &0AD2E, each by
                type, one after another, and ram_cost_at, by level, where
                the level's table starts in them (the ST's pointers at
                &0AE1E, levels 0 to 15)

The ST indexes each by type with no bound, so a type past a table's end
reads on into what follows it; the 32 entries of size_y and ram_score do
the same here. Types 30 and 31 never ram (30's box is 0; nothing makes a
31), so ram_cost keeps only the ST's 30 a table.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import st_prg  # noqa: E402

TYPES = 32
SIZE_Y = 0x0ACF2
RAM_SCORE = 0x0AED6
RAM_COST = 0x0AD2E          # the four tables, 30 words each
RAM_COST_TYPES = 30
RAM_COST_TABLES = 4
RAM_COST_BY_LEVEL = 0x0AE1E  # 16 pointers
LEVELS = 16


def words(prg, at, n):
    return [prg.u16(at + 2 * i) for i in range(n)]


def table(name, values):
    return [f".{name}_lo", "    EQUB " + ", ".join(f"&{v & 0xFF:02X}" for v in values),
            f".{name}_hi", "    EQUB " + ", ".join(f"&{v >> 8:02X}" for v in values)]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    prg = st_prg.load(sys.argv[1])
    outdir = Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True)
    at = []
    for level in range(LEVELS):
        p = prg.u32(RAM_COST_BY_LEVEL + 4 * level)
        k, r = divmod(p - RAM_COST, 2 * RAM_COST_TYPES)
        if r or not 0 <= k < RAM_COST_TABLES:
            sys.exit(f"level {level}'s ram cost table at &{p:05X} isn't one of the four")
        at.append(k * RAM_COST_TYPES)
    src = ["\\ Generated by tools/mkcollide.py from the ST's STAR.PRG: do not edit.",
           f"RAM_COST_LEVELS = {LEVELS}"]
    src += table("size_y", words(prg, SIZE_Y, TYPES))
    src += table("ram_score", words(prg, RAM_SCORE, TYPES))
    src += table("ram_cost", words(prg, RAM_COST, RAM_COST_TABLES * RAM_COST_TYPES))
    src += [".ram_cost_at", "    EQUB " + ", ".join(str(a) for a in at)]
    (outdir / "collide.6502").write_text("\n".join(src) + "\n")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate the ground dots' rotation into camera space, for ground_dots'
decision and their drawing (Baron source).

    mkground.py > build/gen/ground.6502

A ground dot is at the ground's height, so of the nine terms of the ST's
camera rotation (&04092, the logic's rotate_exact) column y's three are
the same for every dot in a frame: ground_setup works them out, exactly,
once, with the rest of each row's constant. The other six (rows x', y',
z' by columns x and z) are products by the frame's matrix, specialised
as rotate_exact's are (tools/mkrotate.py): D = d + 32768, unsigned, and a
16-bit multiplier M = 4|m| whose bytes are patched into the product's
table reads, so that floor(m d / 16384) is the high word of M D, plus
-2m (and for m < 0, negated: the high word's ceiling).

Each term takes M's high byte by D's, and the high bytes only of M's low
byte by D's high and M's high by D's low, each read without the borrow
from its low byte: the high word less the carries the dropped bytes would
have made (0 to 2), and plus the borrows (0 or 1 each), which about
cancel. A term is within 2 of the ST's (tools/groundcheck.py checks every
m and d), a coordinate within 4: ground_dots decides by that bound, the
exact rotation deciding only within it of the cone's edges, and a dot is
drawn within a pixel by it when its offset is NEAR_D or more on x or z
(view_under.6502, which rotates the nearer ones exactly, measures it:
tools/viewrun.mjs). An entry of +-16384 (M = 65536) takes M = &FFFF and 1
more in the constant. The sign of each term picks its add or subtract,
patched.
"""

out = []


def emit(s=""):
    out.append(s)


# each term's patch sites: (label, what goes there)
SITES = [("a", "mh"), ("b", "~mh"), ("c", "mh"), ("d", "~mh"),
         ("g", "mh"), ("h", "~mh"),
         ("k", "ml"), ("l", "~ml")]
OPS = ["op0", "op1", "op2"]             # the flag, then the low and high byte's add or subtract
# the six terms: (row, column), column x's first
TERMS = [(r, c) for c in (0, 2) for r in range(3)]

emit("""\\ Generated by tools/mkground.py: do not edit.

ZA_AUTO1 gr_lo, gr_hi, gr_t         ; a term's high word, and a byte of it
""")
emit("\\ each kind of patch site's offsets from its term's start (gt0's)")
for kind, name in (("mh", "MH"), ("~mh", "NMH"), ("ml", "ML"), ("~ml", "NML")):
    emit(f"GT_{name} = {{" + ", ".join(f"gt0_{k} + 1 - gt0" for k, v in SITES if v == kind) + "}")
for o in OPS:
    emit(f"GT_{o.upper()} = gt0_{o} - gt0")
for t in range(1, 6):
    for k in [k for k, _ in SITES] + OPS:
        emit(f"ASSERT gt{t}_{k} - gt{t} = gt0_{k} - gt0")
emit()

emit("""\\ ground_setup: ground_rotate specialised to cam, for dots at rot_d+2
\\ (dy) below the camera: each term's M and sign patched, and each row's
\\ constant, its column y's term (the ST's, exactly) with the terms' -2m
\\ and their roundings.
.ground_setup
{
    ZA_AUTO2 m, k, t, p
    ZA_AUTO1 term
    LDX #5
.each
    STX term
    LDA gt_entry,X : TAY
    LDA cam,Y : ZA_INDEXEDBY {0, 4, 6, 10, 12, 16}
    STA m : LDA cam+1,Y : ZA_INDEXEDBY {0, 4, 6, 10, 12, 16}
    STA m+1
    LDA gt_lo,X : STA p : LDA gt_hi,X : STA p+1
    \\ -2m into the row's constant, and for a subtract 1 less, the
    \\ ceiling (the dropped carries and borrows about cancel)
    LDA m : ASL A : STA t : LDA m+1 : ROL A : STA t+1
    LDY gt_row,X
    LDA kacc,Y
    SEC : SBC t : STA kacc,Y
    LDA kacc+1,Y
    SBC t+1 : STA kacc+1,Y
    BIT m+1 : BPL rounded
    LDA kacc,Y
    SEC : SBC #1 : STA kacc,Y
    LDA kacc+1,Y
    SBC #0 : STA kacc+1,Y
.rounded
    \\ M = 4|m|, and the add or subtract
    LDA #&18 : STA k : LDA #&65 : STA k+1       ; CLC, ADC zp
    LDA m+1 : BPL positive
    LDA #0 : SEC : SBC m : STA m : LDA #0 : SBC m+1 : STA m+1
    LDA #&38 : STA k : LDA #&E5 : STA k+1       ; SEC, SBC zp
.positive
    LDY #GT_OP0 : LDA k : STA (p),Y
    LDY #GT_OP1 : LDA k+1 : STA (p),Y
    LDY #GT_OP2 : STA (p),Y
    ASL m : ROL m+1 : ASL m : ROL m+1
    BCC fits
    \\ 65536: &FFFF, and 1 more
    LDA #&FF : STA m : STA m+1
    LDY gt_row,X
    LDA kacc,Y
    CLC : ADC #1 : STA kacc,Y
    BCC fits
    LDA kacc+1,Y
    ADC #0 : STA kacc+1,Y
.fits""")


def patch(var, name, complement):
    emit(f"    LDA {var}" + (" : EOR #&FF" if complement else ""))
    emit(f"    FOR o = GT_{name}")
    emit("        LDY #o : STA (p),Y")
    emit("    NEXT")


patch("m+1", "MH", False)
patch("m+1", "NMH", True)
patch("m", "ML", False)
patch("m", "NML", True)
emit("""    LDX term
    DEX : BPL more
    \\ the constants, into the rows' first values
    LDA kacc : STA gk0+1 : LDA kacc+1 : STA gk1+1
    LDA kacc+2 : STA gk2+1 : LDA kacc+3 : STA gk3+1
    LDA kacc+4 : STA gk4+1 : LDA kacc+5 : STA gk5+1
    RTS
.more
    JMP each
}

\\ ground_start: each row's constant begun with its column y's term,
\\ floor(m dy / 16384) (the ST's), before ground_setup adds the rest.
.ground_start
{
    LDX #4
.each
    LDA gt_y_entry,X : TAY
    LDA cam,Y : ZA_INDEXEDBY {2, 8, 14}
    STA mul_x : LDA cam+1,Y : ZA_INDEXEDBY {2, 8, 14}
    STA mul_x+1
    LDA rot_d+2 : STA mul_y : LDA rot_d+3 : STA mul_y+1
    PHX
    JSR fmul16
    PLX
    LDA mul_r : STA kacc,X
    LDA mul_r+1 : STA kacc+1,X
    DEX : DEX : BPL each
    RTS
}
""")
emit("\\ by term: its entry of cam, its row's offset in rot_acc, and its code")
emit(".gt_entry")
emit("    EQUB " + ", ".join(str(2 * (3 * r + c)) for r, c in TERMS))
emit(".gt_row")
emit("    EQUB " + ", ".join(str(2 * r) for r, _ in TERMS))
emit(".gt_lo")
emit("    EQUB " + ", ".join(f"LO(gt{t})" for t in range(6)))
emit(".gt_hi")
emit("    EQUB " + ", ".join(f"HI(gt{t})" for t in range(6)))
emit("\\ column y's entries, by row (rot_acc's offset)")
emit(".gt_y_entry")
emit("    EQUB 2, 0, 8, 0, 14")
emit("\\ the rows' constants as they're made (in the bank's own RAM: the draw")
emit("\\ phase leaves zero page little room)")
emit(".kacc SKIP 6")
emit()



def term(t):
    """Term t's product, added to or subtracted from its row (patched)."""
    r, c = TERMS[t]
    emit(f"\\ term {t}: {'xyz'[r]}' on {'xyz'[c]}")
    emit(f".gt{t}")
    emit("    SEC")
    emit(f".gt{t}_a")
    emit("    LDA sqr_lo,Y")
    emit(f".gt{t}_b")
    emit("    SBC neg_lo,Y : STA gr_lo           ; M's high byte by D's high")
    emit(f".gt{t}_c")
    emit("    LDA sqr_hi,Y")
    emit(f".gt{t}_d")
    emit("    SBC neg_hi,Y : STA gr_hi")
    emit("    SEC                                ; M's high byte by D's low: its high byte")
    emit(f".gt{t}_g")
    emit("    LDA sqr_hi,X")
    emit(f".gt{t}_h")
    emit("    SBC neg_hi,X : STA gr_t")
    emit("    SEC                                ; M's low byte by D's high: its high byte")
    emit(f".gt{t}_k")
    emit("    LDA sqr_hi,Y")
    emit(f".gt{t}_l")
    emit("    SBC neg_hi,Y")
    emit("    CLC : ADC gr_t")
    emit(f"    BCC gc{t}")
    emit("    INC gr_hi : CLC")
    emit(f".gc{t}")
    emit("    ADC gr_lo : STA gr_lo")
    emit(f"    BCC gd{t}")
    emit("    INC gr_hi")
    emit(f".gd{t}")
    emit(f"    LDA rot_acc+{2 * r}")
    emit(f".gt{t}_op0")
    emit("    CLC                                ; patched: CLC or SEC ...")
    emit(f".gt{t}_op1")
    emit(f"    ADC gr_lo : STA rot_acc+{2 * r}       ; ... ADC or SBC")
    emit(f"    LDA rot_acc+{2 * r + 1}")
    emit(f".gt{t}_op2")
    emit(f"    ADC gr_hi : STA rot_acc+{2 * r + 1}")


emit("""\\ ground_x, ground_y, ground_z: one row of rot_acc = cam rot_d, x', y' or
\\ z', for a dot at the ground, within 2 of the ST's (ground_setup made
\\ them for this frame's cam and dy), a row at a time so that a dot can be
\\ given up before its other rows. X and Y are a column's D, low and high
\\ byte.""")
for r in range(3):
    emit(f".ground_{'xyz'[r]}")
    emit(f".gk{2 * r}")
    emit(f"    LDA #0 : STA rot_acc+{2 * r}             ; patched: the row's constant")
    emit(f".gk{2 * r + 1}")
    emit(f"    LDA #0 : STA rot_acc+{2 * r + 1}")
    for c in (0, 2):
        emit(f"    LDX rot_d+{2 * c}                      ; column {'xyz'[c]}'s D")
        emit(f"    LDA rot_d+{2 * c + 1} : EOR #&80 : TAY")
        term(TERMS.index((r, c)))
    emit("    RTS")
print("\n".join(out))
